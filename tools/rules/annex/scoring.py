"""Siege candidate eligibility, score adjustments and supply-failure cooldowns.

Builds the vanilla scoring wrapper and its action-end hook. Annex-specific value
adjustments are emitted by valuation.py after the shared candidate filters.
"""
from rules.common import *  # noqa: F401,F403
from rules.annex.valuation import _annex_value


SUP_BLOCK = 120    # s: after a launch ended InsufficientSupply the faction gets no siege target this long (60: Fremen
                   # failed again right after, 11 in one match, match 2026-10-24 05:30)
BK_LIB, BK_ANX, BK_PIL = 1.5, 1.3, 0.4  # base-kill plan: the leader's villages by siege kind (liberate > annex > pillage)
# base-kill foothold (user: annex a village near the base first, a foothold to heal at, if there is Authority): a
# level-2 member with Authority >= FOOT_AUTH and no structure within FOOT_R of the leader's base scores the Annex
# candidates FOOT_MIN..FOOT_R from that base x FOOT_W (rules/bkill.py then stages there: our structure nearest the
# base, >= BC_STAGE_MIN 250 from it, is the staging point; our own land heals)
FOOT_MIN, FOOT_R, FOOT_W, FOOT_AUTH = 90, 350, 3.0, 150  # 90-350: outside the base guns (range 80), near enough
                                                        # (user 2026-10-25: Dal-nit, 102 from Tuek, was the foothold)
                                                         # to be the strike point (user: foothold near the base)
TK_BLOCK = 90      # s: ... and after one of its sieges was cancelled before Action because another order took an army


def build_supply_block(cx, helpers, new_ids):
    """`supblk`: AIMilitary.onActionEnd (every call site outside our wrappers) -> wrapper: an action ended
    InsufficientSupply (vanilla's path supply check at launch: the lowest army supply below the trip's cost) marks map
    `supf` faction -> now; the scoring wrapper then gives that faction no siege target for SUP_BLOCK, so its armies
    resupply first. Fremen at ~0 water launched a new Pillage every 30 s, 7 in a row dead at launch, each pulling
    5-9 armies off their orders (match 2026-10-24 03:40). Logs `supblk` (f, k)."""
    oe = cx.fn('logic.ai.AIMilitary.onActionEnd')
    ft = cx.code.types[oe.type.value].definition
    names = [c.name.resolve(cx.code) for c in cx.code.types[ft.args[2].value].definition.constructs]
    isup = names.index('InsufficientSupply')
    fb = FB(cx, [x.value for x in ft.args], ft.ret.value, fun_type=oe.type.value)
    b = B(fb)
    r = fb.reg(ft.ret.value)
    fb.op('CallN', dst=r, fun=oe.findex.value, args=list(range(len(ft.args))))  # vanilla, outside the trap
    guard = fb.try_()
    fb.op('JNull', reg=2, offset='end')
    ix = fb.reg(cx.t('i32'))
    fb.op('EnumIndex', dst=ix, value=2)
    fb.op('JNotEq', a=ix, b=b.const('i32', isup), offset='end')
    fac = b.field(b.field(0, 'controller'), 'owner')
    fb.op('JNull', reg=fac, offset='end')
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, 'supf'), fb.dyn(fac), fb.dyn(b.field(_state(fb, b, cx), 'time')))
    _log_ev(fb, b, cx, helpers, 'supblk', [('f', fb.get(fac, 'kind')), ('k', 1)])
    fb.label('end')
    fb.end_try(guard)
    fb.op('Ret', ret=r)
    w = fb.build()
    new_ids.add(w)
    n = 0
    for f in cx.code.functions:  # every caller but this wrapper (the ai-log trace wrapper too: it chains)
        if f.findex.value == w:
            continue
        for op in f.ops:
            if op.op.startswith('Call') and op.df.get('fun') is not None and op.df['fun'].value == oe.findex.value:
                op.df['fun'].value = w
                n += 1
    if not n:
        raise ValueError('supblk: no onActionEnd call site')
    return {'supply-block': n}


def build_scoring(cx, new_ids, helpers):
    """Target scores: the single tryAction -> $HScoring.structures(structures, faction, k, ...) call (target
    scores for Annex / Liberate / Pillage / ...) -> wrapper:
    - supply / busy block: no target at all for SUP_BLOCK after a launch of the faction ended InsufficientSupply
      (`supblk`), or for TK_BLOCK after one of its sieges was cancelled before Action because another order (a Defense)
      took one of its armies (map `tkc`, rules/orders.py take-keep);
    - untargetable: a structure Entity.canBeAttacked(faction) refuses (Cease Fire and the like) is dropped (`untgt`);
    - lost lately: a target where one of our captures lost half its armies in Action within SX_MEM (rules/tasks.py
      siege memory, map `sxf`) is dropped (`sxblock`);
    - retry: a structure vanilla launched a siege on less than its block ago is dropped (RETRY, doubled up to
      RETRY_MAX per relaunch right after the block ran out: a launch that keeps failing at once backs off). While its order runs vanilla
      doesn't re-pick it, so a re-pick means that order ended at once: fillAttackSteps cancels in Waiting with
      InsufficientSupply (the lowest army supply < AIOrders.estimateSupplyCost of the path) and the gauge, still
      full, re-picked the same village every ~2.5 s (Fremen Pelmah x39). Logs `space` why retry (10 s throttle);
    - stuck: FAIL_N launches on it within FAIL_WIN that created no order while an army of ours was free to go (map
      `afu` blocked-until, set by the launch wrapper) -> dropped for FAIL_BLOCK..FAIL_MAX s, logs `space` why stuck;
    - next Annex choices (map `akeep`, rules/raid.py annex-keep: top RAID_KEEP within AKEEP_T): no Pillage target;
    - DMZ (rules/dmz.py, aimod_dmzv): Pillage drops a DMZ village, its Annex / Liberate score x DMZ_W;
    - bunker preference: a positive score x BUNKER_W when the structure is within COVER_R of one of our structures
      on our land (their turrets cover each other) or within BUNKER_R of our main base.
    Original scores on any error."""
    orig = cx.fn('logic.ai.$HScoring.structures')
    ft = cx.code.types[orig.type.value].definition
    args = [a.value for a in ft.args]
    fb = FB(cx, args, ft.ret.value, fun_type=orig.type.value)
    b = B(fb)
    res = fb.reg(ft.ret.value)
    fb.op('CallN', dst=res, fun=orig.findex.value, args=list(range(len(args))))
    guard = fb.try_()
    fb.op('JNull', reg=res, offset='end')
    fb.op('JNull', reg=0, offset='end')
    fb.op('JNull', reg=1, offset='end')
    n = b.field(0, 'length')
    # supply block (build_supply_block): a launch of this faction ended InsufficientSupply within SUP_BLOCK: no target
    # busy block (orders.py take-keep, map `tkc`): one of our sieges lost an army to another order before Action and
    # was cancelled within TK_BLOCK: no target either
    spq = fb.reg(cx.t('f64'))
    for mname, lim in (('supf', SUP_BLOCK), ('tkc', TK_BLOCK)):
        nx = _uid('spm')
        spv = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, mname), fb.dyn(1))
        fb.op('JNull', reg=spv, offset=nx)
        fb.op('SafeCast', dst=spq, src=spv)
        fb.op('Sub', dst=spq, a=b.field(_state(fb, b, cx), 'time'), b=spq)
        fb.op('JSLte', a=spq, b=b.const('f64', lim), offset='sp_go')
        fb.label(nx)
    fb.op('JAlways', offset='sp_no')
    fb.label('sp_go')
    spi = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=spi, src=b.const('i32', 0))
    b.loop_head('sp')
    fb.op('JSGte', a=spi, b=n, offset='end')
    spe = b.call('hl.types.ArrayObj.getDyn', 0, spi)
    fb.op('Incr', dst=spi)
    fb.op('JNull', reg=spe, offset='sp')
    b.call('haxe.ds.ObjectMap.remove', res, spe)
    fb.op('JAlways', offset='sp')
    fb.label('sp_no')
    # base-kill plan (rules/bkill.py, level >= 1, user: partner up against the leader): villages of other at-war
    # owners are no siege targets (neutral ones and the leader's stay). Logs `bkpart` (f, vs, n dropped) per 60 s
    bkt = _bk_target(fb, b, cx, 1, 'bk_d')
    bki, bkn = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    bke_ = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=bki, src=b.const('i32', 0))
    fb.op('Mov', dst=bkn, src=b.const('i32', 0))
    b.loop_head('bk')
    fb.op('JSGte', a=bki, b=n, offset='bk_l')
    fb.op('Mov', dst=bke_, src=b.cast(b.call('hl.types.ArrayObj.getDyn', 0, bki), 'ent.Entity'))
    fb.op('Incr', dst=bki)
    fb.op('JNull', reg=bke_, offset='bk')
    bko = b.call('ent.Entity.get_owner', bke_)
    fb.op('JNull', reg=bko, offset='bk')
    fb.op('JEq', a=bko, b=bkt, offset='bk')
    fb.op('JEq', a=bko, b=1, offset='bk')
    # a plan partner's village too, at peace or not: vanilla keeps a truce partner's village when it can declare war
    # and its launch declares it (AIOrder completion closure; user 2026-10-24: Smugglers / Harkonnen dropped their
    # coalition peace mid-campaign)
    _bk_partner(fb, b, cx, 1, bko, 'bk_rm')
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', _state(fb, b, cx), 1, bko), offset='bk')
    fb.label('bk_rm')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(bke_))
    fb.op('Incr', dst=bkn)
    fb.op('JAlways', offset='bk')
    fb.label('bk_l')
    # the leader's villages: take them, don't burn them (user: Smugglers pillaged the clear leader Fremen; liberating
    # cuts its hegemony and leaves a neutral buffer, annexing near its base stages the kill): Liberate x BK_LIB,
    # Annex x BK_ANX, Pillage x BK_PIL (still possible when it's the only choice)
    bkf = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=bkf, src=_ratio(fb, b, BK_PIL))
    fb.op('JNotEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Pillage'))), b=b.const('i32', 0), offset='bkf_l')
    fb.op('JAlways', offset='bkf_go')
    fb.label('bkf_l')
    fb.op('Mov', dst=bkf, src=_ratio(fb, b, BK_LIB))
    fb.op('JEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Liberate'))), b=b.const('i32', 0), offset='bkf_go')
    fb.op('Mov', dst=bkf, src=_ratio(fb, b, BK_ANX))
    fb.op('JEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Annex'))), b=b.const('i32', 0), offset='bkf_go')
    fb.op('JAlways', offset='bkf_d')
    fb.label('bkf_go')
    bksc = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=bki, src=b.const('i32', 0))
    b.loop_head('bkf')
    fb.op('JSGte', a=bki, b=n, offset='bkf_d')
    fb.op('Mov', dst=bke_, src=b.cast(b.call('hl.types.ArrayObj.getDyn', 0, bki), 'ent.Entity'))
    fb.op('Incr', dst=bki)
    fb.op('JNull', reg=bke_, offset='bkf')
    fb.op('JNotEq', a=b.call('ent.Entity.get_owner', bke_), b=bkt, offset='bkf')
    bkv_ = b.call('haxe.ds.ObjectMap.get', res, fb.dyn(bke_))
    fb.op('JNull', reg=bkv_, offset='bkf')
    fb.op('SafeCast', dst=bksc, src=bkv_)
    fb.op('JSLte', a=bksc, b=b.const('f64', 0), offset='bkf')  # a vetoed / negative score stays as it is
    fb.op('Mul', dst=bksc, a=bksc, b=bkf)
    b.call('haxe.ds.ObjectMap.set', res, fb.dyn(bke_), fb.dyn(bksc))
    fb.op('JAlways', offset='bkf')
    fb.label('bkf_d')
    # foothold (FOOT_*): an Annex candidate near the leader's base while we have no structure there
    fb.op('JNotEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Annex'))), b=b.const('i32', 0), offset='bft_d')
    ftv = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'bkv'), fb.dyn(1))
    fb.op('JNull', reg=ftv, offset='bft_d')
    fti = fb.reg(cx.t('i32'))
    fb.op('SafeCast', dst=fti, src=ftv)
    fb.op('JSLt', a=fti, b=b.const('i32', 2), offset='bft_d')
    fb.op('JSLt', a=b.call('ent.Faction.getResource', 1, b.const('i32', RES_AUTHORITY)), b=b.const('f64', FOOT_AUTH),
          offset='bft_d')
    ftb = b.call('ent.Faction.get_mainBase', bkt)
    fb.op('JNull', reg=ftb, offset='bft_d')
    ftbe = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=ftbe, src=ftb)
    fts = b.cast(fb.get(1, 'structures', 'array'), 'hl.types.ArrayObj')
    fb.op('JNull', reg=fts, offset='bft_d')
    ftk = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=ftk, src=b.const('i32', 0))
    fse = fb.reg(cx.t('ent.Entity'))
    b.loop_head('bft_s')
    fb.op('JSGte', a=ftk, b=b.field(fts, 'length'), offset='bft_sd')
    fss = b.cast(b.call('hl.types.ArrayObj.getDyn', fts, ftk), 'ent.Structure')
    fb.op('Incr', dst=ftk)
    fb.op('JNull', reg=fss, offset='bft_s')
    fb.op('Mov', dst=fse, src=fss)
    fb.op('JSLte', a=b.call('ent.Entity.getDistTo', fse, ftbe), b=b.const('f64', FOOT_R), offset='bft_d')  # have one
    fb.op('JAlways', offset='bft_s')
    fb.label('bft_sd')
    ftn = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=ftn, src=b.const('i32', 0))
    ftd = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=bki, src=b.const('i32', 0))
    b.loop_head('bft')
    fb.op('JSGte', a=bki, b=n, offset='bft_l')
    fb.op('Mov', dst=bke_, src=b.cast(b.call('hl.types.ArrayObj.getDyn', 0, bki), 'ent.Entity'))
    fb.op('Incr', dst=bki)
    fb.op('JNull', reg=bke_, offset='bft')
    fb.op('Mov', dst=ftd, src=b.call('ent.Entity.getDistTo', bke_, ftbe))
    fb.op('JSLt', a=ftd, b=b.const('f64', FOOT_MIN), offset='bft')
    fb.op('JSGt', a=ftd, b=b.const('f64', FOOT_R), offset='bft')
    ftsv = b.call('haxe.ds.ObjectMap.get', res, fb.dyn(bke_))
    fb.op('JNull', reg=ftsv, offset='bft')
    fb.op('SafeCast', dst=bksc, src=ftsv)
    fb.op('JSLte', a=bksc, b=b.const('f64', 0), offset='bft')
    fb.op('Mul', dst=bksc, a=bksc, b=_ratio(fb, b, FOOT_W))
    b.call('haxe.ds.ObjectMap.set', res, fb.dyn(bke_), fb.dyn(bksc))
    fb.op('Incr', dst=ftn)
    fb.op('JAlways', offset='bft')
    fb.label('bft_l')
    fb.op('JSLte', a=ftn, b=b.const('i32', 0), offset='bft_d')
    _throttle(fb, b, cx, 'bfoot', 1, 60, 'bft_d')
    _log_ev(fb, b, cx, helpers, 'bfoot', [('f', fb.get(1, 'kind')), ('base', ftbe), ('n', fb.dyn(ftn)),
                                          ('auth', b.call('ent.Faction.getResource', 1, b.const('i32', RES_AUTHORITY)))])
    fb.label('bft_d')
    fb.op('JSLte', a=bkn, b=b.const('i32', 0), offset='bk_d')
    _throttle(fb, b, cx, 'bkpart', 1, 60, 'bk_d')
    _log_ev(fb, b, cx, helpers, 'bkpart', [('f', fb.get(1, 'kind')), ('vs', fb.get(bkt, 'kind')), ('n', fb.dyn(bkn))])
    fb.label('bk_d')
    # untargetable (any siege kind): a structure we can't attack now (Entity.canBeAttacked: attributes 626 / 628 / 629,
    # e.g. a Cease Fire) is dropped. Vanilla picked it, the launch pulled armies out of their Resupply / Patrol, and
    # checkOrderTerminations cancelled it 1 s later; then it re-picked it (Fremen Liberate of Smugglers' Ofir / Rab-san
    # 3 x each, Harkonnen's of Arsdak / Lam-dah, match 2026-10-24 00:17). Logs `untgt` (f, s) per structure per 60 s
    ui = fb.reg(cx.t('i32'))
    use = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=ui, src=b.const('i32', 0))
    b.loop_head('ut')
    fb.op('JSGte', a=ui, b=n, offset='utd')
    fb.op('Mov', dst=use, src=b.cast(b.call('hl.types.ArrayObj.getDyn', 0, ui), 'ent.Entity'))
    fb.op('Incr', dst=ui)
    fb.op('JNull', reg=use, offset='ut')
    fb.op('JTrue', cond=b.call('ent.Entity.canBeAttacked', use, 1), offset='ut')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(use))
    _throttle(fb, b, cx, 'untgt', use, 60, 'ut')
    _log_ev(fb, b, cx, helpers, 'untgt', [('f', fb.get(1, 'kind')), ('s', use), ('k', 2)])
    fb.op('JAlways', offset='ut')
    fb.label('utd')
    # lost lately (rules/tasks.py siege memory, map `sxf` per faction: target -> when one of our captures there lost
    # half its armies in Action): dropped for SX_MEM (Harkonnen re-ran Waldah / Admara 4 x each). Logs `sxblock`
    sxm = _fac_map(fb, b, cx, 'sxf', 1)
    sxt = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=sxt, src=b.field(_state(fb, b, cx), 'time'))
    fb.op('Mov', dst=ui, src=b.const('i32', 0))
    b.loop_head('sx')
    fb.op('JSGte', a=ui, b=n, offset='sxd')
    fb.op('Mov', dst=use, src=b.cast(b.call('hl.types.ArrayObj.getDyn', 0, ui), 'ent.Entity'))
    fb.op('Incr', dst=ui)
    fb.op('JNull', reg=use, offset='sx')
    sxv = b.call('haxe.ds.ObjectMap.get', sxm, fb.dyn(use))
    fb.op('JNull', reg=sxv, offset='sx')
    sxq = fb.reg(cx.t('f64'))
    fb.op('SafeCast', dst=sxq, src=sxv)
    fb.op('Sub', dst=sxq, a=sxt, b=sxq)
    fb.op('JSGt', a=sxq, b=b.const('f64', SX_MEM), offset='sx')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(use))
    _throttle(fb, b, cx, 'sxblock', use, 60, 'sx')
    _log_ev(fb, b, cx, helpers, 'sxblock', [('f', fb.get(1, 'kind')), ('s', use), ('k', 2), ('age', sxq)])
    fb.op('JAlways', offset='sx')
    fb.label('sxd')
    # Liberate reach (user: Fremen held back): vanilla's Liberation picks the daily target's villages anywhere on the
    # map (Annex / Pillage are held to supply reach); a candidate farther than LIB_REACH from our land is dropped
    # unless a free Supply Drop (map `sdfree`) or a worm ride (`wfree`) makes the trip. Fremen launched 5 Liberates
    # 508-843 out at 27-28 min, all dead at launch (InsufficientSupply / NotEnoughArmies) while an Annex waited for
    # armies (match 2026-10-23 22:4x). Logs `lreach` (f, n dropped) per faction per 60 s
    fb.op('JNotEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Liberate'))), b=b.const('i32', 0), offset='nolib')
    lt = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=lt, src=b.field(_state(fb, b, cx), 'time'))
    lrf = fb.reg(cx.t('bool'))  # a worm ride is free: far candidates stay unless their ride plan failed lately
    fb.op('Bool', dst=lrf, value=False)
    _ride_free(fb, b, cx, 1, lt, 'lr_nw')
    fb.op('Bool', dst=lrf, value=True)
    fb.op('JAlways', offset='lr_go')
    fb.label('lr_nw')
    lsv = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'sdfree'), fb.dyn(1))
    fb.op('JNull', reg=lsv, offset='lr_go')
    lsq = fb.reg(cx.t('f64'))
    fb.op('SafeCast', dst=lsq, src=lsv)
    fb.op('Sub', dst=lsq, a=lt, b=lsq)
    fb.op('JSLte', a=lsq, b=b.const('f64', SD_FRESH), offset='nolib')
    fb.label('lr_go')
    li, ldrop = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    fb.op('Mov', dst=li, src=b.const('i32', 0))
    fb.op('Mov', dst=ldrop, src=b.const('i32', 0))
    lse = fb.reg(cx.t('ent.Entity'))
    ld = fb.reg(cx.t('f64'))
    b.loop_head('lr')
    fb.op('JSGte', a=li, b=n, offset='lrd')
    fb.op('Mov', dst=lse, src=b.cast(b.call('hl.types.ArrayObj.getDyn', 0, li), 'ent.Entity'))
    fb.op('Incr', dst=li)
    fb.op('JNull', reg=lse, offset='lr')
    fb.op('Call2', dst=ld, fun=helpers['land'], arg0=1, arg1=lse)
    fb.op('JSLte', a=ld, b=b.const('f64', LIB_REACH), offset='lr')
    # with a free ride: only a target whose ride plan failed within UNREACH_T (map `wbad`: InvalidThumperSlots, the
    # walk fallback then failed the supply check: Fremen's Liberates of Aidesek / Markus died 1 s after launch, each
    # pulling 7-12 armies off their orders, match 2026-10-24 01:03)
    fb.op('JFalse', cond=lrf, offset='lr_rm')
    lwb = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'wbad'), fb.dyn(lse))
    fb.op('JNull', reg=lwb, offset='lr')
    lwq = fb.reg(cx.t('f64'))
    fb.op('SafeCast', dst=lwq, src=lwb)
    fb.op('Sub', dst=lwq, a=lt, b=lwq)
    fb.op('JSGte', a=lwq, b=b.const('f64', UNREACH_T), offset='lr')
    fb.label('lr_rm')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(lse))
    fb.op('Incr', dst=ldrop)
    fb.op('JAlways', offset='lr')
    fb.label('lrd')
    fb.op('JSLte', a=ldrop, b=b.const('i32', 0), offset='nolib')
    _throttle(fb, b, cx, 'lreach', 1, 60, 'nolib')
    ldf = fb.reg(cx.t('f64'))
    fb.op('ToSFloat', dst=ldf, src=ldrop)
    _log_ev(fb, b, cx, helpers, 'lreach', [('f', fb.get(1, 'kind')), ('n', ldf)])
    fb.label('nolib')
    # press (rules/strat.py): the gates are opened for the pressed village's owner only; among its villages only the
    # pressed one stays; its Annex score x PRESS_W in annex mode (vanilla picks at random among the top scores), and
    # it is no Annex target in pillage mode (`raid` takes it)
    pvd = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'spv'), fb.dyn(1))
    fb.op('JNull', reg=pvd, offset='nopress')
    pfp = b.cast(b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'spf'), fb.dyn(1)), 'ent.Faction')
