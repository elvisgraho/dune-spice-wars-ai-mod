def _log_hunt(fb, b, cx, helpers, fac, act, why, tgt, h, m, extra):
    d = fb.reg(cx.t('dynobj'))
    fb.op('New', dst=d)
    b.put(d, 'e', fb.string('hunt'))
    b.put(d, 'f', fb.get(fac, 'kind'))
    b.put(d, 'act', fb.string(act))
    if why:
        b.put(d, 'why', fb.string(why))
    tent = fb.reg(cx.t('dyn'))
    fb.op('Call1', dst=tent, fun=helpers['ent'], arg0=fb.dyn(tgt))
    b.put(d, 'tgt', tent)
    b.put(d, 'H', b.to_int(h))
    b.put(d, 'M', b.to_int(m))
    for k, r in extra.items():
        if fb.regs[r] == cx.t('ent.Entity'):
            er = fb.reg(cx.t('dyn'))
            fb.op('Call1', dst=er, fun=helpers['ent'], arg0=fb.dyn(r))
            b.put(d, k, er)
        else:
            b.put(d, k, b.to_int(r) if fb.regs[r] == cx.t('f64') else r)
    b.put(d, 'x', b.to_int(b.field(tgt, 'posx')))
    b.put(d, 'y', b.to_int(b.field(tgt, 'posy')))
    v = fb.reg(cx.t('void'))
    fb.op('Call1', dst=v, fun=helpers['log'], arg0=fb.dyn(d))


def _near_base(fb, b, cx, state, fac, e, mbr, wr):
    """mbr = the active main base of a faction at war with fac nearest to entity e within BASE_KEEP (else null),
    wr = its proximity 1 - d / BASE_KEEP (0..1)."""
    k, j = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    me, d = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('f64'))
    zi = b.const('i32', 0)
    lf, lm, ok = _uid('nbf'), _uid('nbm'), _uid('nbok')
    fb.op('Null', dst=mbr)
    fb.op('Mov', dst=wr, src=b.const('f64', 0))
    facs = b.cast(fb.get(state, 'factions', 'array'), 'hl.types.ArrayObj')
    fb.op('JNull', reg=facs, offset=ok)
    fb.op('Mov', dst=k, src=zi)
    b.loop_head(lf)
    fb.op('JSGte', a=k, b=b.field(facs, 'length'), offset=ok)
    of = b.cast(b.call('hl.types.ArrayObj.getDyn', facs, k), 'ent.Faction')
    fb.op('Incr', dst=k)
    fb.op('JNull', reg=of, offset=lf)
    fb.op('JEq', a=of, b=fac, offset=lf)
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', state, fac, of), offset=lf)
    mbs = b.field(of, 'mainBases')
    fb.op('JNull', reg=mbs, offset=lf)
    fb.op('Mov', dst=j, src=zi)
    b.loop_head(lm)
    fb.op('JSGte', a=j, b=b.field(mbs, 'length'), offset=lf)
    mb = b.cast(b.call('hl.types.ArrayObj.getDyn', mbs, j), 'ent.Structure')
    fb.op('Incr', dst=j)
    fb.op('JNull', reg=mb, offset=lm)
    fb.op('JFalse', cond=b.call('ent.Structure.get_isActiveMainBase', mb), offset=lm)
    fb.op('Mov', dst=me, src=mb)
    fb.op('Mov', dst=d, src=b.call('ent.Entity.getDistTo', e, me))
    fb.op('SDiv', dst=d, a=d, b=b.const('f64', BASE_KEEP))
    fb.op('Sub', dst=d, a=b.const('f64', 1), b=d)
    fb.op('JSLte', a=d, b=wr, offset=lm)
    fb.op('Mov', dst=wr, src=d)
    fb.op('Mov', dst=mbr, src=me)
    fb.op('JAlways', offset=lm)
    fb.label(ok)


def _late(fb, b, cx, v, d, t, late_lbl, ok_lbl, fall=False):
    """Contest arrival test (start and `objective` abort alike): jump to late_lbl when an army d away (CONTEST_SPD)
    arrives after the occupation at village v ends (+ CONTEST_SLACK), else to ok_lbl (fall=True: ok falls through).
    Remaining time: _cap_rem (rules/common.py); a capture making no progress is never late. Returns the (arrival, remaining, progress) registers."""
    u = _uid('lt')
    lq = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=lq, src=b.const('f64', 0))
    lrem, lp = _cap_rem(fb, b, cx, v, t, u + 'ok')  # stalled / no siege: never late, worth contesting
    fb.op('SDiv', dst=lq, a=d, b=b.const('f64', CONTEST_SPD))
    fb.op('Add', dst=lrem, a=lrem, b=b.const('f64', CONTEST_SLACK))
    fb.op('JSGt', a=lq, b=lrem, offset=late_lbl)
    fb.label(u + 'ok')
    if not fall:
        fb.op('JAlways', offset=ok_lbl)
    return lq, lrem, lp


def build_hunt(cx, helpers, pw, free, hthreat, land, terrain, supok, short, sieged, cover, defend, neutral, react):
    """aimod_hunt(mil, dt): abort pass every CHECK s, start pass every START s (see module doc). Threat is always
    aimod_hthreat around the prey's faction (a third party at war with it doesn't count, one allied with it only
    if it arrives before we finish), and the target group holds only that faction's armies, the one nearest the
    anchor first: Engage walks every hunter to group.entities[0] and they fight nobody else on the way."""
    fb = FB(cx, [cx.t('logic.ai.AIMilitary'), cx.t('f64')], cx.t('void'))
    b = B(fb)
    void = fb.reg(cx.t('void'))
    guard = fb.try_()
    ctrl = b.field(0, 'controller')
    fac = b.field(ctrl, 'owner')
    fb.op('JNull', reg=fac, offset='end')
    state = _state(fb, b, cx)
    t = b.field(state, 'time')
    armies = b.field(state, 'armies')
    alen = b.field(armies, 'length')
    villages = b.field(state, 'villages')
    fb.op('JNull', reg=villages, offset='end')
    vlen = b.field(villages, 'length')
    my_armies, mlen = _my_armies(fb, b, fac, 'end')
    orders_obj = b.field(ctrl, 'aiOrders')
    orders = b.field(orders_obj, 'orders')
    fb.op('JNull', reg=orders, offset='end')
    no_orders = fb.reg(cx.t('hl.types.ArrayObj'))
    fb.op('Null', dst=no_orders)
    hunt_r, local = b.const('f64', HUNT_R), b.const('f64', LOCAL)
    home_r, home_exit = b.const('f64', HOME_R), b.const('f64', HOME_EXIT)
    defend_r, leash = b.const('f64', DEFEND_R), b.const('f64', LEASH)
    contact, drift_r = b.const('f64', CONTACT), b.const('f64', DRIFT_R)
    enter, abort = _ratio(fb, b, ENTER), _ratio(fb, b, ABORT)
    sup_enter = _ratio(fb, b, SUP_ENTER)
    gather_r = b.const('f64', GATHER_R)
    kill = _ratio(fb, b, KILL)
    kill_x = _ratio(fb, b, KILL / ENTER)  # need (= ENTER x threat / terrain) x this = KILL x threat / terrain
    dfs = fb.reg(cx.t('ent.Structure'))  # our besieged structure (defensive posture), else null
    tc, tm, q, tv = (fb.reg(cx.t('f64')) for _ in range(4))  # enemy / own turret cover, scratch, scratch
    no_ent = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=no_ent)
    t_false, t_true = fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    fb.op('Bool', dst=t_false, value=False)
    fb.op('Bool', dst=t_true, value=True)

    def cover_at(dst, at, exclude, own):
        fb.op('CallN', dst=dst, fun=cover, args=[fac, at, exclude, t_true if own else t_false, no_orders])
    pf = fb.reg(cx.t('ent.Faction'))  # the prey's faction (null: neutral raiders / unknown besieger)

    def threat_at(dst, at, dn):
        fb.op('CallN', dst=dst, fun=hthreat, args=[fac, at, local, pf, dn])

    def besieger(s):
        """pf = the faction besieging structure s, else its occupier (aimod_sieged's measure; null: raiders)."""
        lbl = f'bs{len(fb.ops)}'
        fb.op('Null', dst=pf)
        sg = b.field(s, 'siege')
        fb.op('JNull', reg=sg, offset=lbl)
        fb.op('Mov', dst=pf, src=b.field(sg, 'besiegingFaction'))
        fb.op('JNotNull', reg=pf, offset=lbl)
        fb.op('Mov', dst=pf, src=b.call('ent.comp.SiegeComponent.getOccupierFaction', sg))
        fb.label(lbl)
    gap = b.const('f64', HUNT_GAP)
    zero, zi, one = b.const('f64', 0), b.const('i32', 0), b.const('i32', 1)
    big = b.const('f64', 1 << 30)
    i, j, k = fb.reg(cx.t('i32')), fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    p, h, m, need, sd, sdx, tf = (fb.reg(cx.t('f64')) for _ in range(7))
    cnt, war, vis, home, nn = (fb.reg(cx.t('i32')) for _ in range(5))
    ok, losing, neu = fb.reg(cx.t('bool')), fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    ent_r = fb.reg(cx.t('ent.Entity'))
    first = fb.reg(cx.t('ent.Entity'))
    core = fb.reg(cx.t('ent.Entity'))  # abort pass: the live member nearest our land (sd); the group is judged there
    ve, found = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity'))
    idx = fb.reg(cx.t('i32'))
    lastmap = _global_map(fb, b, cx, 'hunt')
    objmap = _global_map(fb, b, cx, 'hobj')
    # chase progress per order: time of the last progress, prey power and our distance to it at that moment
    pt_map, pp_map, pd_map = (_global_map(fb, b, cx, n) for n in ('hpt', 'hpp', 'hpd'))
    pp = fb.reg(cx.t('f64'))  # live prey power (group members)
    prog, close = _ratio(fb, b, 1 - PROGRESS), b.const('f64', CLOSE)
    rtf, rpf, rdf = (fb.reg(cx.t('f64')) for _ in range(3))
    givemap = _global_map(fb, b, cx, 'hgive')  # army -> time a chase on it was given up
    gvf = fb.reg(cx.t('f64'))

    tripd, tripl = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    trip_e = fb.reg(cx.t('ent.Entity'))

    def _trip(a, da, back, dst):
        """dst = back + min(da, back + land(a)): the off-land walk to the anchor (da from army a) + the way back."""
        fb.op('Mov', dst=trip_e, src=a)
        fb.op('Call2', dst=tripl, fun=land, arg0=fac, arg1=trip_e)
        fb.op('Add', dst=tripl, a=tripl, b=back)
        lbl = _uid('trip')
        fb.op('Mov', dst=dst, src=da)
        fb.op('JSLte', a=dst, b=tripl, offset=lbl)
        fb.op('Mov', dst=dst, src=tripl)
        fb.label(lbl)
        fb.op('Add', dst=dst, a=dst, b=back)

    hax, hay, hat = (_global_map(fb, b, cx, n) for n in ('hax', 'hay', 'hat'))
    ax_, ay_ = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))

    def given_up(e, skip):
        """Jump to `skip` if a chase on army e was given up less than GIVEUP_T s ago (it outruns us), or e stands
        within LOCAL of where a hunt of ours aborted on supply / weak / turret / desert less than HUNT_AREA_T s ago."""
        gv = b.call('haxe.ds.ObjectMap.get', givemap, fb.dyn(e))
        lbl, la = f'gu{len(fb.ops)}', _uid('ga')
        fb.op('JNull', reg=gv, offset=lbl)
        fb.op('SafeCast', dst=gvf, src=gv)
        fb.op('Sub', dst=gvf, a=t, b=gvf)
        fb.op('JSLt', a=gvf, b=b.const('f64', GIVEUP_T), offset=skip)
        fb.label(lbl)
        av = b.call('haxe.ds.ObjectMap.get', hat, fb.dyn(fac))
        fb.op('JNull', reg=av, offset=la)
        fb.op('SafeCast', dst=gvf, src=av)
        fb.op('Sub', dst=gvf, a=t, b=gvf)
        fb.op('JSGte', a=gvf, b=b.const('f64', HUNT_AREA_T), offset=la)
        fb.op('SafeCast', dst=ax_, src=b.call('haxe.ds.ObjectMap.get', hax, fb.dyn(fac)))
        fb.op('SafeCast', dst=ay_, src=b.call('haxe.ds.ObjectMap.get', hay, fb.dyn(fac)))
        fb.op('Sub', dst=ax_, a=b.field(e, 'posx'), b=ax_)
        fb.op('Sub', dst=ay_, a=b.field(e, 'posy'), b=ay_)
        fb.op('Mul', dst=ax_, a=ax_, b=ax_)
        fb.op('Mul', dst=ay_, a=ay_, b=ay_)
        fb.op('Add', dst=ax_, a=ax_, b=ay_)
        fb.op('JSLt', a=ax_, b=b.const('f64', LOCAL * LOCAL), offset=skip)
        fb.label(la)

    # ---- 1. abort pass: re-check running hunts (backwards: stop() removes the order from the list)
    _tick(fb, b, cx, t, CHECK, 'new')
    fb.op('Call1', dst=dfs, fun=defend, arg0=fac)
    reason = cx.code.types[cx.fn('logic.ai.AIOrder.stop').type.value].definition.args[1].value
    cancel = fb.reg(reason)
    fb.op('MakeEnum', dst=cancel, construct=CANCEL, args=[])
    fb.op('Mov', dst=i, src=b.field(orders, 'length'))
    b.loop_head('ord')
    fb.op('JSLte', a=i, b=zi, offset='new')
    fb.op('Sub', dst=i, a=i, b=one)
    o = b.cast(b.call('hl.types.ArrayObj.getDyn', orders, i), 'logic.ai.AIOrder')
    fb.op('JNull', reg=o, offset='ord')
    fb.op('EnumIndex', dst=idx, value=b.field(o, 'type'))
    fb.op('JNotEq', a=idx, b=b.const('i32', MILITARY), offset='ord')
    tt = b.field(o, 'targetType')
    fb.op('JNull', reg=tt, offset='ord')
    fb.op('EnumIndex', dst=idx, value=tt)
    fb.op('JNotEq', a=idx, b=b.const('i32', T_GROUP), offset='ord')
    g = b.cast(b.call('logic.ai.AIOrder.getTarget', o), 'logic.ai.AIEntityGroup')
    fb.op('JNull', reg=g, offset='ab_nolog')
    fb.op('Mov', dst=ent_r, src=g)
    fb.op('Mov', dst=first, src=g)
    fb.op('Mov', dst=core, src=g)
    for r in (h, m, pp):
        fb.op('Mov', dst=r, src=zero)
    for r in (cnt, war, vis, home, nn):
        fb.op('Mov', dst=r, src=zi)
    fb.op('Mov', dst=sd, src=big)
    fb.op('Mov', dst=tc, src=zero)
    fb.op('JTrue', cond=b.field(g, 'removed'), offset='ab_gone')
    # members: alive / at war with us / visible / on their owner's own zone
    mem = b.field(g, 'entities')
    fb.op('JNull', reg=mem, offset='ab_gone')
    mn = b.field(mem, 'length')
    fb.op('Mov', dst=j, src=zi)
    b.loop_head('mem')
    fb.op('JSGte', a=j, b=mn, offset='mdone')
    e = b.cast(b.call('hl.types.ArrayObj.getDyn', mem, j), 'ent.Entity')
    fb.op('Incr', dst=j)
    fb.op('JNull', reg=e, offset='mem')
    fb.op('JTrue', cond=b.call('ent.Entity.isDead', e), offset='mem')
    fb.op('Bool', dst=neu, value=False)
    eo = b.call('ent.Entity.get_owner', e)
    fb.op('JNotNull', reg=eo, offset='mown')
    fb.op('JNull', reg=fb.get(e, 'raid'), offset='mem')  # a neutral raider (neutral hunt): hostile, no home
    fb.op('Bool', dst=neu, value=True)
    fb.op('Add', dst=nn, a=nn, b=one)
    fb.label('mown')
    fb.op('Add', dst=cnt, a=cnt, b=one)
    fb.op('Call1', dst=p, fun=pw, arg0=b.cast(e, 'ent.Army'))
    fb.op('Add', dst=pp, a=pp, b=p)
    fb.op('Mov', dst=first, src=e)
    fb.op('Call2', dst=sdx, fun=land, arg0=fac, arg1=e)
    fb.op('JSGte', a=sdx, b=sd, offset='nomin')
    fb.op('Mov', dst=sd, src=sdx)
    fb.op('Mov', dst=core, src=e)
    fb.label('nomin')
    fb.op('JTrue', cond=neu, offset='mwar')
    fb.op('JEq', a=eo, b=fac, offset='nowar')  # areAtWar(us, us) logs a vanilla warning per call
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', state, fac, eo), offset='nowar')
    fb.label('mwar')
    fb.op('Add', dst=war, a=war, b=one)
    fb.label('nowar')
    fb.op('JFalse', cond=b.call('ent.Entity.isVisibleForFaction', e, fac), offset='novis')
    fb.op('Add', dst=vis, a=vis, b=one)
    fb.label('novis')
    fb.op('JTrue', cond=neu, offset='mem')
    z = b.call('ent.Entity.get_zone', e)
    fb.op('JNull', reg=z, offset='mem')
    fb.op('JNotEq', a=b.field(z, 'owner'), b=eo, offset='mem')
    fb.op('Add', dst=home, a=home, b=one)
    fb.op('JAlways', offset='mem')
    fb.label('mdone')
    # the group is judged at its core (the member nearest our land, sd), not at its centroid: a member walking home
    # dragged the centroid under its own base's guns and aborted a winning hunt as `weak`. Members more than LOCAL
    # from the core have split off: they leave the group, so the order's target (centroid) stays on the prey
    fb.op('Mov', dst=first, src=core)
    fb.op('Mov', dst=ent_r, src=core)
    fb.op('Mov', dst=j, src=mn)
    b.loop_head('prune')
    fb.op('JSLte', a=j, b=zi, offset='pdone')
    fb.op('Sub', dst=j, a=j, b=one)
    pe = b.cast(b.call('hl.types.ArrayObj.getDyn', mem, j), 'ent.Entity')
    fb.op('JNull', reg=pe, offset='prune')
    fb.op('JSLte', a=b.call('ent.Entity.getDistTo', pe, core), b=local, offset='prune')
    b.call('hl.types.ArrayObj.remove', mem, fb.dyn(pe))
    fb.op('JTrue', cond=b.call('ent.Entity.isDead', pe), offset='prune')
    fb.op('Call1', dst=p, fun=pw, arg0=b.cast(pe, 'ent.Army'))
    fb.op('Sub', dst=pp, a=pp, b=p)  # progress is measured on the members that stay
    fb.op('JAlways', offset='prune')
    fb.label('pdone')
    # our side: power, nearest order army to the core, anyone short of supply for the way back
    units = b.field(o, 'units')
    fb.op('JNull', reg=units, offset='ab_gone')
    un = b.field(units, 'length')
    fb.op('Mov', dst=need, src=big)
    fb.op('Bool', dst=losing, value=False)
    # in transit (worm ride / shuttle): no re-decision until it lands; _army_loop skips transported armies, so
    # power read 0 (Fremen: 6 armies riding to contest Hadwaz, M 0, aborted `weak`, landed orderless as it fell)
    _riding(fb, b, cx, helpers, fac, o, units, 'hride', 'ord')
    u = _army_loop(fb, b, units, un, j, 'units', 'udone')
    fb.op('Call1', dst=p, fun=pw, arg0=u)
    fb.op('Add', dst=m, a=m, b=p)
    fb.op('Call2', dst=ok, fun=short, arg0=fac, arg1=u)
    fb.op('JFalse', cond=ok, offset='sup')  # hysteresis: the start needs SUP_ENTER x the budget
    fb.op('Bool', dst=losing, value=True)
    fb.label('sup')
    dd = b.call('ent.Entity.getDistTo', u, core)
    fb.op('JSGte', a=dd, b=need, offset='units')
    fb.op('Mov', dst=need, src=dd)
    fb.op('JAlways', offset='units')
    fb.label('udone')
    # triggers, in priority order (sd = the member nearest to our land, same measure as the start pass)
    fb.op('JSLte', a=cnt, b=zi, offset='ab_gone')
    fb.op('JSLte', a=war, b=zi, offset='ab_truce')
    fb.op('JSGt', a=sd, b=leash, offset='ab_leash')
    fb.op('JNotEq', a=home, b=cnt, offset='nothome')
    fb.op('JSGt', a=sd, b=home_exit, offset='ab_home')
    fb.label('nothome')
    fb.op('JSLte', a=sd, b=drift_r, offset='nodrift')  # moving away from our land and we never caught up
    fb.op('JSGt', a=need, b=contact, offset='ab_drift')
    fb.label('nodrift')
    fb.op('JSGt', a=vis, b=zi, offset='seen')
    fb.op('JSGt', a=need, b=local, offset='ab_lost')
    fb.label('seen')
    fb.op('Mov', dst=pf, src=b.call('ent.Entity.get_owner', core))  # the group is one faction (start pass)
    threat_at(h, ent_r, need)
    fb.op('JSLte', a=nn, b=zi, offset='noneu')  # neutral prey: raiders busy elsewhere fight back too
    fb.op('Call3', dst=q, fun=neutral, arg0=fac, arg1=ent_r, arg2=local)
    fb.op('Add', dst=h, a=h, b=q)
    fb.label('noneu')
    # turret cover at the group: enemy turrets / main base guns add to the threat, ours to our power
    cover_at(tc, ent_r, no_ent, False)
    cover_at(tm, ent_r, no_ent, True)
    # an enemy main base ahead: its defense weighs in before its guns reach us, growing from 0 at BASE_KEEP to all
    # of it at the base (soft: a strong enough stack still goes; Atreides' 8 armies chased a dying Fremen group from
    # Qalnih to 123 from Tabr on draining supply and were wiped out after). The larger of it and the cover at the
    # group: within gun range the base is already in that
    nbm, nbw = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('f64'))
    _near_base(fb, b, cx, state, fac, core, nbm, nbw)
    fb.op('JNull', reg=nbm, offset='nbdone')
    cover_at(q, nbm, no_ent, False)
    fb.op('Mul', dst=q, a=q, b=nbw)
    fb.op('JSLte', a=q, b=tc, offset='nbdone')
    fb.op('Mov', dst=tc, src=q)
    fb.label('nbdone')
    fb.op('Add', dst=h, a=h, b=tc)
    fb.op('Add', dst=m, a=m, b=tm)
    fb.op('Mul', dst=p, a=h, b=abort)
    fb.op('Call2', dst=tf, fun=terrain, arg0=fac, arg1=b.call('ent.Entity.get_zone', first))
    fb.op('SDiv', dst=p, a=p, b=tf)  # on their land we give up earlier, on ours later
    fb.op('JSLt', a=m, b=p, offset='ab_weak')
    # supply: turn back while the way home is affordable, in contact too, unless we are on the prey and crush it
    # (KILL x its threat: a few seconds to finish it; a stack walked home from a nearly dead army and gave it up).
    # A prey without power (a harvester) is no quick kill: KILL x 0 always held, and 2 Smugglers S_Troopers shot a
    # deployed F_Harvester for 30 s (hp -12 / 10 s) on hostile sand while supply fell 83 -> 26
    fb.op('JFalse', cond=losing, offset='supok')
