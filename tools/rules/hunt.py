    fb.op('Mov', dst=ae, src=anc)
    fb.op('Call2', dst=tq, fun=helpers['tension'], arg0=fac, arg1=ae)
    fb.op('Mul', dst=tq, a=tq, b=_ratio(fb, b, ENTER - TEN_ENTER))
    fb.op('Sub', dst=enx, a=enx, b=tq)
    fb.label('tx')
    fb.op('Mul', dst=need, a=h, b=enx)
    fb.op('Call2', dst=tf, fun=terrain, arg0=fac, arg1=b.call('ent.Entity.get_zone', anc))
    fb.op('SDiv', dst=need, a=need, b=tf)  # their land: 1.5 / 0.8 = 1.9x needed; ours: 1.15x
    fb.op('JSLt', a=m, b=need, offset='next')
    # contest size floor, as the sizing applies it (armies alone >= DEF_HOPE_IN x max(threat, aimod_react + cover) /
    # terrain): a contest failing it at sizing after winning the pick (contests outrank chases) blocked every chase
    fb.op('JNotEq', a=mode, b=one, offset='cfloor')
    fb.op('Call3', dst=q, fun=react, arg0=fac, arg1=prey, arg2=local)
    fb.op('Add', dst=q, a=q, b=tc)
    fb.op('JSGte', a=q, b=h, offset='cfmax')
    fb.op('Mov', dst=q, src=h)
    fb.label('cfmax')
    fb.op('SDiv', dst=q, a=q, b=tf)
    fb.op('Mul', dst=q, a=q, b=_ratio(fb, b, DEF_HOPE_IN))
    fb.op('Sub', dst=p, a=m, b=tm)  # armies alone
    fb.op('JSLt', a=p, b=q, offset='next')
    fb.label('cfloor')
    # a chase while we defend, or under enemy turret cover: only when the prey is in contact and we have KILL x
    # (its threat + cover)
    fb.op('JEq', a=mode, b=one, offset='score')
    fb.op('JTrue', cond=far, offset='restrict')
    fb.op('JNotNull', reg=dfs, offset='restrict')
    fb.op('JSLte', a=tc, b=zero, offset='score')
    fb.label('restrict')
    fb.op('JSGt', a=dmin, b=contact, offset='next')
    fb.op('Mul', dst=q, a=need, b=kill_x)
    fb.op('JSLt', a=m, b=q, offset='next')
    fb.label('score')
    # score = threat / (distance of our nearest free army + DIST0)^2: the enemy in front of us first (linear distance
    # let a stack twice as strong twice as far win while another walked past under our noses); contests (goal 4)
    # outrank every chase (goal 5) by CONTEST_W, else the `objective` abort cancels the chase it picked
    fb.op('Add', dst=sc, a=dmin, b=dist0)
    fb.op('Mul', dst=sc, a=sc, b=sc)
    fb.op('SDiv', dst=sc, a=h, b=sc)
    fb.op('JNotEq', a=mode, b=one, offset='scx')
    fb.op('JTrue', cond=minor, offset='scx')
    fb.op('Add', dst=sc, a=sc, b=contest_w)
    fb.label('scx')
    fb.op('JSLte', a=sc, b=best_s, offset='next')
    fb.op('Mov', dst=best_s, src=sc)
    fb.op('Mov', dst=best_d, src=dmin)
    fb.op('Mov', dst=best_h, src=h)
    fb.op('Mov', dst=best_m, src=m)
    fb.op('Mov', dst=best_sd, src=sd)
    fb.op('Mov', dst=best_rr, src=rr)
    fb.op('Mov', dst=best_t, src=tc)
    fb.op('Mov', dst=best, src=prey)
    fb.op('Mov', dst=best_anc, src=anc)
    fb.op('Mov', dst=best_mode, src=mode)
    fb.op('Mov', dst=best_pf, src=pf)
    fb.op('Mov', dst=best_far, src=far)
    fb.label('next')
    fb.op('JEq', a=mode, b=one, offset='vcand')
    fb.op('JEq', a=mode, b=two, offset='ncand')
    fb.op('JAlways', offset='cand')
    # (c) neutral candidates, only when no at-war chase or contest qualifies ("after the enemy"): visible
    # raiders (rebels, Fremen raids, marauders, ...) near our land (they raid our villages), or anywhere in
    # contact of our free armies when we crush them (far: KILL test, like a chase under turret cover)
    fb.label('vdone')
    fb.op('JNotNull', reg=best, offset='chosen')
    fb.op('Mov', dst=mode, src=two)
    e = _army_loop(fb, b, armies, alen, i, 'ncand', 'chosen')
    fb.op('JNotNull', reg=b.call('ent.Entity.get_owner', e), offset='ncand')
    fb.op('JNull', reg=b.field(e, 'raid'), offset='ncand')
    fb.op('JFalse', cond=b.call('ent.Entity.isVisibleForFaction', e, fac), offset='ncand')
    given_up(e, 'ncand')
    fb.op('Mov', dst=ent_r, src=e)
    fb.op('Call2', dst=sd, fun=land, arg0=fac, arg1=ent_r)
    fb.op('Bool', dst=far, value=False)
    fb.op('JSLte', a=sd, b=defend_r, offset='nnear')
    fb.op('Bool', dst=far, value=True)
    fb.label('nnear')
    fb.op('Null', dst=pf)
    fb.op('Mov', dst=anc, src=e)
    fb.op('Mov', dst=prey, src=e)
    fb.op('Mov', dst=w, src=one_f)
    fb.op('Mov', dst=rr, src=hunt_r)
    fb.op('JAlways', offset='eval')
    fb.label('chosen')
    fb.op('JNull', reg=best, offset='end')
    fb.op('Mov', dst=sd, src=best_sd)  # logged sd = the chosen anchor's

    # target = group of the prey faction's armies around the anchor (the besieged village for a contest, else the
    # prey; neutral hunt: the raiders there), the one nearest the anchor first: Engage walks every hunter to
    # entities[0] and they fight nobody else on the way (a mixed group sent Harkonnen towards an Atreides stack past
    # the Fremen prey). Vanilla checkStructures pattern; the group drops dead members and removes itself when
    # empty; checkEngageOrder requires a Group target for ArmyFight
    def member(lp, ok):
        """Fall through to label `ok` if army x of loop `lp` belongs in the group, else jump back to `lp`."""
        xo = b.call('ent.Entity.get_owner', x)
        fb.op('JNotNull', reg=xo, offset=f'{lp}own')
        fb.op('JEq', a=best_mode, b=two, offset=f'{lp}rd')
        fb.op('JNotEq', a=best_mode, b=one, offset=lp)
        fb.op('JNotNull', reg=best_pf, offset=lp)  # contest of a raider siege (no besieging faction): its raiders
        fb.label(f'{lp}rd')
        fb.op('JNull', reg=b.field(x, 'raid'), offset=lp)
        fb.op('JSGt', a=b.call('ent.Entity.getDistTo', x, best_anc), b=local, offset=lp)
        fb.op('JAlways', offset=ok)
        fb.label(f'{lp}own')
        fb.op('JEq', a=xo, b=fac, offset=lp)
        fb.op('JSGt', a=b.call('ent.Entity.getDistTo', x, best_anc), b=local, offset=lp)
        fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', state, fac, xo), offset=lp)
        # no prey faction (raider-siege contest, neutral hunt): raiders only. A Fremen F_Harvester 201 from
        # Atreides' Qartnah joined a raider contest, outlived the raiders and was chased (H 0) to a `supply` abort, twice
        fb.op('JNull', reg=best_pf, offset=lp)
        fb.op('JNotEq', a=xo, b=best_pf, offset=lp)
        fb.label(ok)
    nx = fb.reg(cx.t('ent.Army'))
    fb.op('Null', dst=nx)
    nd = b.const('f64', 1 << 30)
    x = _army_loop(fb, b, armies, alen, j, 'grp1', 'grp1done')
    member('grp1', 'g1ok')
    dx_ = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=dx_, src=b.call('ent.Entity.getDistTo', x, best_anc))
    # an armed member first: Atreides walked 7 armies past a 155k escort to a 0-power F_Harvester 110 from it
    gpw = fb.reg(cx.t('f64'))
    fb.op('Call1', dst=gpw, fun=pw, arg0=x)
    fb.op('JSGt', a=gpw, b=b.const('f64', 0), offset='g1arm')
    fb.op('Add', dst=dx_, a=dx_, b=b.const('f64', 1 << 20))
    fb.label('g1arm')
    fb.op('JSGte', a=dx_, b=nd, offset='grp1')
    fb.op('Mov', dst=nd, src=dx_)
    fb.op('Mov', dst=nx, src=x)
    fb.op('JAlways', offset='grp1')
    fb.label('grp1done')
    fb.op('JNotNull', reg=nx, offset='grp1ok')
    # siege state but no besieger in reach: logged, an `objective` abort may have released a chase for this (Fremen
