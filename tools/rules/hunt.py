    fb.op('Call1', dst=dq, fun=pw, arg0=ny)
    fb.op('Add', dst=mt, a=mt, b=dq)
    fb.op('JSGte', a=mt, b=goal, offset='seldone')
    # contest: up to the goal however many armies that takes (no cap / gate stop), all in reach if it isn't met.
