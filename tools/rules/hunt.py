    fb.op('JFalse', cond=ok, offset='gloop')
    fb.op('Mov', dst=ny, src=y)
    fb.op('Mov', dst=nd2, src=dg)
    fb.op('JAlways', offset='gloop')
    fb.label('gdone')
    fb.op('JNull', reg=ny, offset='seldone')
