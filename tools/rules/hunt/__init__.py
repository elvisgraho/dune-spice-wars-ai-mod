"""Hunts: running-order checks followed by at most one new chase or contest.

build_hunt owns register allocation, shared callbacks and the new-hunt pass.
running emits checks for existing hunts into the same builder using explicit
keyword inputs. support owns shared logging, base proximity and arrival checks.
"""
from rules.common import *  # noqa: F401,F403
from rules import bkstate as bks
from rules.worm import _move_to
from rules.hunt.support import HUNT_FC_T, _log_hunt, _near_base, _late
from rules.hunt.running import _emit_running


def build_hunt(cx, helpers, pw, free, hthreat, land, terrain, supok, short, sieged, cover, defend, neutral,
               owner_pw):
    """aimod_hunt(mil, dt): abort pass every CHECK s, start pass every START s (see module doc). Threat is always
    aimod_hthreat around the prey's faction (a third party at war with it doesn't count, one allied with it only
    if it arrives before we finish), and the target group holds only that faction's armies, the one nearest the
    anchor first: Engage walks every hunter to group.entities[0] and they fight nobody else on the way."""
    fb = FB(cx, [cx.t('logic.ai.AIMilitary'), cx.t('f64')], cx.t('void'))
    b = B(fb)
    void = fb.reg(cx.t('void'))
    eta_fn = helpers['eta']  # rules/travel.py
    guard = fb.try_()
    _crumb_begin(fb, b, cx, helpers, 'hunt')  # step probe: `rfail` names a run that died silently
    ctrl = b.field(0, 'controller')
    fac = b.field(ctrl, 'owner')
    fb.op('JNull', reg=fac, offset='end')
    state = _state(fb, b, cx)
    t = b.field(state, 'time')
    armies = b.field(state, 'armies')
    alen = b.field(armies, 'length')
    villages = b.field(state, 'villages')
    fb.op('JNull', reg=villages, offset='end')
    vlen = b.field(villages, 'length')
    my_armies, mlen = _my_armies(fb, b, fac, 'end')
    orders_obj = b.field(ctrl, 'aiOrders')
    orders = b.field(orders_obj, 'orders')
    fb.op('JNull', reg=orders, offset='end')
    no_orders = fb.reg(cx.t('hl.types.ArrayObj'))
    fb.op('Null', dst=no_orders)
    hunt_r, local = b.const('f64', HUNT_R), b.const('f64', LOCAL)
    home_r, home_exit = b.const('f64', HOME_R), b.const('f64', HOME_EXIT)
    defend_r, leash = b.const('f64', DEFEND_R), b.const('f64', LEASH)
    contest_r = b.const('f64', CONTEST_R)
    contact, drift_r = b.const('f64', CONTACT), b.const('f64', DRIFT_R)
    enter, abort = _ratio(fb, b, ENTER), _ratio(fb, b, ABORT)
    sup_enter = _ratio(fb, b, SUP_ENTER)
    gather_r = b.const('f64', GATHER_R)
    kill = _ratio(fb, b, KILL)
    kill_x = _ratio(fb, b, KILL / ENTER)  # need (= ENTER x threat / terrain) x this = KILL x threat / terrain
    dfs = fb.reg(cx.t('ent.Structure'))  # our besieged structure (defensive posture), else null
    tc, tm, q, tv = (fb.reg(cx.t('f64')) for _ in range(4))  # enemy / own turret cover, scratch, scratch
    no_ent = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=no_ent)
    t_false, t_true = fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    fb.op('Bool', dst=t_false, value=False)
    fb.op('Bool', dst=t_true, value=True)

    def cover_at(dst, at, exclude, own):
        fb.op('CallN', dst=dst, fun=cover, args=[fac, at, exclude, t_true if own else t_false, no_orders])
    pf = fb.reg(cx.t('ent.Faction'))  # the prey's faction (null: neutral raiders / unknown besieger)

    def threat_at(dst, at, dn):
        fb.op('CallN', dst=dst, fun=hthreat, args=[fac, at, local, pf, dn])

    def besieger(s):
        """pf = the faction besieging structure s, else its occupier (aimod_sieged's measure; null: raiders)."""
        lbl = f'bs{len(fb.ops)}'
        fb.op('Null', dst=pf)
        sg = b.field(s, 'siege')
        fb.op('JNull', reg=sg, offset=lbl)
        fb.op('Mov', dst=pf, src=b.field(sg, 'besiegingFaction'))
        fb.op('JNotNull', reg=pf, offset=lbl)
        fb.op('Mov', dst=pf, src=b.call('ent.comp.SiegeComponent.getOccupierFaction', sg))
        fb.label(lbl)
    gap = b.const('f64', HUNT_GAP)
    zero, zi, one = b.const('f64', 0), b.const('i32', 0), b.const('i32', 1)
    big = b.const('f64', 1 << 30)
    i, j, k = fb.reg(cx.t('i32')), fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    p, h, m, need, sd, sdx, tf = (fb.reg(cx.t('f64')) for _ in range(7))
    cnt, war, vis, home, nn = (fb.reg(cx.t('i32')) for _ in range(5))
    ok, losing, neu = fb.reg(cx.t('bool')), fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    ourdd = fb.reg(cx.t('bool'))  # one of the hunt's armies stands in a deep desert zone (abort pass)
    ent_r = fb.reg(cx.t('ent.Entity'))
    first = fb.reg(cx.t('ent.Entity'))
    core = fb.reg(cx.t('ent.Entity'))  # abort pass: the live member nearest our land (sd); the group is judged there
    ve, found = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity'))
    idx = fb.reg(cx.t('i32'))
    lastmap = _global_map(fb, b, cx, 'hunt')
    objmap = _global_map(fb, b, cx, 'hobj')
    # chase progress per order: time of the last progress, prey power and our distance to it at that moment
    pt_map, pp_map, pd_map = (_global_map(fb, b, cx, n) for n in ('hpt', 'hpp', 'hpd'))
    pp = fb.reg(cx.t('f64'))  # live prey power (group members)
    prog, close = _ratio(fb, b, 1 - PROGRESS), b.const('f64', CLOSE)
    rtf, rpf, rdf = (fb.reg(cx.t('f64')) for _ in range(3))
    givemap = _global_map(fb, b, cx, 'hgive')  # army -> time a chase on it was given up
    conmap = _global_map(fb, b, cx, 'hcon')  # contest order -> the village it defends (abort `won`)
    gvf = fb.reg(cx.t('f64'))

    tripd, tripl = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    trip_e = fb.reg(cx.t('ent.Entity'))

    def _trip(a, da, back, dst):
        """dst = back + min(da, back + land(a)): the off-land walk to the anchor (da from army a) + the way back."""
        fb.op('Mov', dst=trip_e, src=a)
        fb.op('Call2', dst=tripl, fun=land, arg0=fac, arg1=trip_e)
        fb.op('Add', dst=tripl, a=tripl, b=back)
        lbl = _uid('trip')
        fb.op('Mov', dst=dst, src=da)
        fb.op('JSLte', a=dst, b=tripl, offset=lbl)
        fb.op('Mov', dst=dst, src=tripl)
        fb.label(lbl)
        fb.op('Add', dst=dst, a=dst, b=back)

    hax, hay, hat = (_global_map(fb, b, cx, n) for n in ('hax', 'hay', 'hat'))
    ax_, ay_ = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))

    def given_up(e, skip):
        """Jump to `skip` if a chase on army e was given up less than GIVEUP_T s ago (it outruns us), or e stands
        within LOCAL of where a hunt of ours aborted on supply / weak / turret / desert less than HUNT_AREA_T s ago."""
        gv = b.call('haxe.ds.ObjectMap.get', givemap, fb.dyn(e))
        lbl, la = f'gu{len(fb.ops)}', _uid('ga')
        fb.op('JNull', reg=gv, offset=lbl)
        fb.op('SafeCast', dst=gvf, src=gv)
        fb.op('Sub', dst=gvf, a=t, b=gvf)
        fb.op('JSLt', a=gvf, b=b.const('f64', GIVEUP_T), offset=skip)
        fb.label(lbl)
        av = b.call('haxe.ds.ObjectMap.get', hat, fb.dyn(fac))
        fb.op('JNull', reg=av, offset=la)
        fb.op('SafeCast', dst=gvf, src=av)
        fb.op('Sub', dst=gvf, a=t, b=gvf)
        fb.op('JSGte', a=gvf, b=b.const('f64', HUNT_AREA_T), offset=la)
        fb.op('SafeCast', dst=ax_, src=b.call('haxe.ds.ObjectMap.get', hax, fb.dyn(fac)))
        fb.op('SafeCast', dst=ay_, src=b.call('haxe.ds.ObjectMap.get', hay, fb.dyn(fac)))
        fb.op('Sub', dst=ax_, a=b.field(e, 'posx'), b=ax_)
        fb.op('Sub', dst=ay_, a=b.field(e, 'posy'), b=ay_)
        fb.op('Mul', dst=ax_, a=ax_, b=ax_)
        fb.op('Mul', dst=ay_, a=ay_, b=ay_)
        fb.op('Add', dst=ax_, a=ax_, b=ay_)
        fb.op('JSLt', a=ax_, b=b.const('f64', LOCAL * LOCAL), offset=skip)
        fb.label(la)

    _emit_running(
        _trip=_trip, abort=abort, b=b, besieger=besieger, big=big, close=close, cnt=cnt,
        conmap=conmap, contact=contact, contest_r=contest_r, core=core, cover_at=cover_at, cx=cx,
        defend=defend, dfs=dfs, drift_r=drift_r, ent_r=ent_r, enter=enter, eta_fn=eta_fn, fac=fac,
        fb=fb, first=first, found=found, free=free, gap=gap, givemap=givemap, h=h, hat=hat,
        hax=hax, hay=hay, helpers=helpers, home=home, home_exit=home_exit, hunt_r=hunt_r, i=i,
        idx=idx, j=j, k=k, kill=kill, land=land, lastmap=lastmap, leash=leash, local=local,
        losing=losing, m=m, need=need, neu=neu, neutral=neutral, nn=nn, no_ent=no_ent,
        no_orders=no_orders, objmap=objmap, ok=ok, one=one, orders=orders, ourdd=ourdd, p=p,
        pd_map=pd_map, pf=pf, pp=pp, pp_map=pp_map, prog=prog, pt_map=pt_map, pw=pw, q=q, rdf=rdf,
        rpf=rpf, rtf=rtf, sd=sd, sdx=sdx, short=short, sieged=sieged, state=state,
        sup_enter=sup_enter, supok=supok, t=t, tc=tc, terrain=terrain, tf=tf, threat_at=threat_at,
        tm=tm, tripd=tripd, tv=tv, ve=ve, villages=villages, vis=vis, vlen=vlen, void=void,
        war=war, zero=zero, zi=zi,
    )

    # ---- 2. start pass: at most one new hunt
    fb.label('new')
    _tick(fb, b, cx, t, START, 'end')
    last = b.call('haxe.ds.ObjectMap.get', lastmap, fb.dyn(fac))
    lastf = fb.reg(cx.t('f64'))
    fb.op('JNull', reg=last, offset='gapok')
    fb.op('SafeCast', dst=lastf, src=last)
    fb.op('Sub', dst=lastf, a=t, b=lastf)
    fb.op('JSLt', a=lastf, b=gap, offset='end')
    fb.label('gapok')
    best_h, best_m, best_s = b.const('f64', 0), b.const('f64', 0), b.const('f64', 0)
    best_d, best_sd = b.const('f64', 0), b.const('f64', 0)
    best = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=best)
    best_pf = fb.reg(cx.t('ent.Faction'))
    fb.op('Null', dst=best_pf)
    anc, best_anc, prey = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=best_anc)
    # capture guard: our captures in Action that the forecast says we lose (gcaps: their targets)
    gtg, best_g = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=gtg)
    fb.op('Null', dst=best_g)
    gcaps = _new_array(fb, b, cx)
    gk, gix = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    gte = fb.reg(cx.t('ent.Entity'))
    gfc = fb.reg(cx.t('f64'))
    gfa = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=gfa, value=True)
    fb.op('JNull', reg=orders, offset='gc_done')
    fb.op('Mov', dst=gk, src=zi)
    b.loop_head('gc')
    fb.op('JSGte', a=gk, b=b.field(orders, 'length'), offset='gc_done')
    go_ = b.cast(b.call('hl.types.ArrayObj.getDyn', orders, gk), 'logic.ai.AIOrder')
    fb.op('Incr', dst=gk)
    fb.op('JNull', reg=go_, offset='gc')
    fb.op('EnumIndex', dst=gix, value=b.field(go_, 'type'))
    fb.op('JNotEq', a=gix, b=b.const('i32', MILITARY), offset='gc')
    fb.op('JNotEq', a=b.field(go_, 'phase'), b=b.const('i32', ACTION), offset='gc')
    gtt = b.field(go_, 'targetType')
    fb.op('JNull', reg=gtt, offset='gc')
    fb.op('EnumIndex', dst=gix, value=gtt)
    fb.op('JNotEq', a=gix, b=b.const('i32', T_STRUCT), offset='gc')
    fb.op('Mov', dst=gte, src=b.call('logic.ai.AIOrder.getTarget', go_))
    fb.op('JNull', reg=gte, offset='gc')
    fb.op('JEq', a=b.call('ent.Entity.get_owner', gte), b=fac, offset='gc')
    gu_ = b.field(go_, 'units')
    fb.op('JNull', reg=gu_, offset='gc')
    fb.op('CallN', dst=gfc, fun=helpers['forecast'], args=[fac, gte, b.const('f64', GUARD_FC_T), gfa, gu_])
    fb.op('JSGte', a=gfc, b=_ratio(fb, b, GUARD_FC), offset='gc')
    b.call('hl.types.ArrayObj.push', gcaps, fb.dyn(gte))
    fb.op('JAlways', offset='gc')
    fb.label('gc_done')
    dmin, w, sc = fb.reg(cx.t('f64')), fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    dmina = fb.reg(cx.t('ent.Entity'))  # the nearest free army (aimod_eta in the arrival test)
    one_f, contest_w, dist0 = b.const('f64', 1), b.const('f64', CONTEST_W), b.const('f64', DIST0)
    mode, best_mode, two = fb.reg(cx.t('i32')), fb.reg(cx.t('i32')), b.const('i32', 2)  # 0 chase 1 contest 2 neutral
    fb.op('Mov', dst=mode, src=zi)
    fb.op('Mov', dst=best_mode, src=zi)
    # minor contest: a village not ours (neutral / a third faction's) farther than CONTEST_NEAR from our land: worth
    # stopping, less than our own or one next to us; no contest priority (scored like a chase), no `objective` abort
    minor = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=minor, value=False)
    far = fb.reg(cx.t('bool'))  # neutral prey away from our land: only in contact and crushing it (KILL)
    best_far = fb.reg(cx.t('bool'))  # the chosen candidate's `far`
    fb.op('Bool', dst=best_far, value=False)
    rr, best_rr = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))  # join radius of the candidate / of the best
    fb.op('Mov', dst=best_rr, src=hunt_r)
    best_t = b.const('f64', 0)  # enemy turret cover at the chosen anchor (logged as T)
    fb.op('Call1', dst=dfs, fun=defend, arg0=fac)
    # right after an `objective` abort only contests may start
    lo = b.call('haxe.ds.ObjectMap.get', objmap, fb.dyn(fac))
    fb.op('JNull', reg=lo, offset='chase')
    fb.op('SafeCast', dst=lastf, src=lo)
    fb.op('Sub', dst=lastf, a=t, b=lastf)
    fb.op('JSLt', a=lastf, b=gap, offset='cdone')
    fb.label('chase')
    # (a) chase candidates: visible at-war armies near our land
    e = _army_loop(fb, b, armies, alen, i, 'cand', 'cdone')
    eo = b.call('ent.Entity.get_owner', e)
    fb.op('JNull', reg=eo, offset='cand')
    fb.op('JEq', a=eo, b=fac, offset='cand')
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', state, fac, eo), offset='cand')
    fb.op('JFalse', cond=b.call('ent.Entity.isVisibleForFaction', e, fac), offset='cand')
    given_up(e, 'cand')
    fb.op('Mov', dst=ent_r, src=e)
    fb.op('Call2', dst=sd, fun=land, arg0=fac, arg1=ent_r)
    # next to a capture of ours we'd lose (gcaps): huntable however far from our land (capture guard)
    fb.op('Null', dst=gtg)
    gj = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=gj, src=zi)
    b.loop_head('gq')
    fb.op('JSGte', a=gj, b=b.field(gcaps, 'length'), offset='gq_d')
    gce = b.cast(b.call('hl.types.ArrayObj.getDyn', gcaps, gj), 'ent.Entity')
    fb.op('Incr', dst=gj)
    fb.op('JNull', reg=gce, offset='gq')
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', gce, ent_r), b=b.const('f64', GUARD_R), offset='gq')
    fb.op('Mov', dst=gtg, src=gce)
    fb.op('JAlways', offset='away')
    fb.label('gq_d')
    fb.op('JSGt', a=sd, b=defend_r, offset='cand')  # only intruders near our land (defensive posture)
    z = b.call('ent.Entity.get_zone', e)
    fb.op('JNull', reg=z, offset='away')
    fb.op('JNotEq', a=b.field(z, 'owner'), b=eo, offset='away')
    fb.op('JSGt', a=sd, b=home_r, offset='cand')  # on its own land: only right next to us
    fb.label('away')
    fb.op('Mov', dst=pf, src=eo)
    fb.op('Mov', dst=anc, src=e)
    fb.op('Mov', dst=prey, src=e)
    fb.op('Mov', dst=w, src=one_f)
    fb.op('Mov', dst=rr, src=hunt_r)
    fb.op('Bool', dst=far, value=False)
    fb.op('JAlways', offset='eval')
    # (b) contest candidates: villages near our land besieged by an at-war faction (objective: weight CONTEST_W,
    # the group is anchored on the village)
    fb.label('cdone')
    fb.op('Null', dst=gtg)
    fb.op('Mov', dst=mode, src=one)
    fb.op('Mov', dst=i, src=zi)
    b.loop_head('vcand')
    fb.op('JSGte', a=i, b=vlen, offset='vdone')
    v = b.cast(b.call('hl.types.ArrayObj.getDyn', villages, i), 'ent.Structure')
    fb.op('Incr', dst=i)
    fb.op('JNull', reg=v, offset='vcand')
    fb.op('Bool', dst=minor, value=False)
    fb.op('Call2', dst=ok, fun=sieged, arg0=fac, arg1=v)
    fb.op('JFalse', cond=ok, offset='vcand')
    # stake: while we defend a capture of ours (aimod_defend), a pillage elsewhere gets no armies: they are the
    # capture's (Atreides sent 3 armies 787 to Sharas' renegade pillage while Fremen closed on Grim-in)
    fb.op('JNull', reg=dfs, offset='vstk')
    fb.op('JEq', a=v, b=dfs, offset='vstk')
    _pillaging(fb, b, cx, dfs, 'vstk')
    _pillaging(fb, b, cx, v, 'vcand')
    fb.label('vstk')
    fb.op('Mov', dst=ent_r, src=v)
    fb.op('Call2', dst=sd, fun=land, arg0=fac, arg1=ent_r)
    # one of our next Annex choices (map `akeep`, rules/raid.py annex-keep, within AKEEP_T) is contested however far
    # (user: Harkonnen pillaged Fremen's next Annex Hulsan 3 times in 25 min; a pillage leaves it Devastated 20 days)
    akx = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=akx, value=False)
    fb.op('Mov', dst=rr, src=hunt_r)
    # an at-war capture within CONTEST_R (DEFEND_R + a short run: Atreides annexed Tab-riyah / Aegkus / Ars-sud
    # 496-548 from Fremen's villages unopposed, user); farther, up to CONTEST_RIDE_R, while a thumper is free (the
    # contest rides: rules/ride.py), and our armies up to HUNT_R + RIDE_LEG away can join (the ride carries them)
    fb.op('JSLte', a=sd, b=contest_r, offset='vnear')
    fb.op('JSGt', a=sd, b=b.const('f64', CONTEST_RIDE_R), offset='vakp')
    _ride_free(fb, b, cx, fac, t, 'vakp')
    fb.op('Mov', dst=rr, src=b.const('f64', HUNT_R + RIDE_LEG))
    fb.op('JAlways', offset='vnear')
    fb.label('vakp')
    # a base-kill partner's village besieged / occupied by the leader: contested however far, like our next Annex
    # (the partner check further down sat behind this distance gate: 13 leader sieges on members' villages and no
    # partner contest, match 2026-10-25 01:05)
    vpg = b.field(v, 'siege')
    fb.op('JNull', reg=vpg, offset='vp_no')
    vpf = fb.reg(cx.t('ent.Faction'))
    fb.op('Mov', dst=vpf, src=b.field(vpg, 'besiegingFaction'))
    fb.op('JNotNull', reg=vpf, offset='vp_have')
    fb.op('Mov', dst=vpf, src=b.call('ent.comp.SiegeComponent.getOccupierFaction', vpg))
    fb.op('JNull', reg=vpf, offset='vp_no')
    fb.label('vp_have')
    vpl = _bk_target(fb, b, cx, fac, 'vp_no')
    fb.op('JNotEq', a=vpf, b=vpl, offset='vp_no')
    vpo = fb.reg(cx.t('ent.Faction'))
    fb.op('Mov', dst=vpo, src=b.call('ent.Entity.get_owner', ent_r))
    fb.op('JNull', reg=vpo, offset='vp_no')
    _bk_partner(fb, b, cx, fac, vpo, 'vp_yes')
    fb.op('JAlways', offset='vp_no')
    fb.label('vp_yes')
    fb.op('Bool', dst=akx, value=True)  # a full contest (not minor)
    fb.op('JAlways', offset='vnear')
    fb.label('vp_no')
    akt = b.call('haxe.ds.ObjectMap.get', _fac_map(fb, b, cx, 'akeep', fac), fb.dyn(v))
    fb.op('JNull', reg=akt, offset='vcand')
    fb.op('SafeCast', dst=q, src=akt)
    fb.op('Sub', dst=q, a=t, b=q)
    fb.op('JSGte', a=q, b=b.const('f64', AKEEP_T), offset='vcand')
    fb.op('Bool', dst=akx, value=True)
    fb.label('vnear')
    # the village we defend (ours, or a neutral one in our home ring: aimod_defend) or any of ours: everyone free
    # within GATHER_R comes (vanilla Regroup gathers them)
    dfe = fb.reg(cx.t('ent.Entity'))
    fb.op('JNull', reg=dfs, offset='vchk')
    fb.op('Mov', dst=dfe, src=dfs)
    fb.op('JEq', a=ent_r, b=dfe, offset='vgath')
    fb.label('vchk')
    fb.op('JNotEq', a=b.call('ent.Entity.get_owner', ent_r), b=fac, offset='notown')
    fb.label('vgath')
    fb.op('Mov', dst=rr, src=gather_r)
    fb.op('JAlways', offset='vown')
    fb.label('notown')
    fb.op('JNotNull', reg=dfs, offset='vcand')  # defending: our own villages first
    fb.op('JSLte', a=sd, b=b.const('f64', CONTEST_NEAR), offset='vown')
    # a base-kill partner's village besieged / occupied by the leader: a full contest (user 2026-10-24: Atreides
