    fb.op('Mul', dst=goal, a=hs, b=kill)
    fb.op('Mov', dst=gate, src=goal)
    fb.label('sz_norm')
    cap = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=cap, src=b.field(garr, 'length'))
    fb.op('Mul', dst=cap, a=cap, b=b.const('i32', HUNT_CAP))
    fb.op('Add', dst=cap, a=cap, b=one)
    # armies alone fill goal and gate, every mode (the evaluation still counts our cover): main-base guns x3 filled
    # both before one army was added, so Harkonnen sent single armies at 58k Rebels by Fonval (order balance 0.01
    # for 40 s); the prey doesn't stay under our guns, the hunt follows it
    fb.op('Mov', dst=mt, src=zero)
    arr = _new_array(fb, b, cx)
    ny = fb.reg(cx.t('ent.Army'))
    nd2 = fb.reg(cx.t('f64'))
    b.loop_head('sel')
    fb.op('Null', dst=ny)
    fb.op('Mov', dst=nd2, src=big)
    y = _army_loop(fb, b, my_armies, mlen, j, 'gloop', 'gdone')
    dg = b.call('ent.Entity.getDistTo', y, best_anc)
    fb.op('JSGt', a=dg, b=best_rr, offset='gloop')
    fb.op('JSGte', a=dg, b=nd2, offset='gloop')
    fb.op('JTrue', cond=b.call('hl.types.ArrayObj.contains', arr, fb.dyn(y)), offset='gloop')
    fb.op('Call2', dst=ok, fun=free, arg0=y, arg1=orders)
    fb.op('JTrue', cond=ok, offset='gfree')
    fb.op('JNotEq', a=best_mode, b=one, offset='gloop')  # a contest takes rally-held armies too (see eval)
    _rallying(fb, b, cx, y, t, 'gfree', 'gloop')
    fb.label('gfree')
    _trip(y, dg, sd, tripd)
    fb.op('Call3', dst=ok, fun=supok, arg0=y, arg1=tripd, arg2=sup_enter)
    fb.op('JFalse', cond=ok, offset='gloop')
    fb.op('Mov', dst=ny, src=y)
    fb.op('Mov', dst=nd2, src=dg)
    fb.op('JAlways', offset='gloop')
    fb.label('gdone')
    fb.op('JNull', reg=ny, offset='seldone')
    b.call('hl.types.ArrayObj.push', arr, fb.dyn(ny))
    fb.op('Call1', dst=dq, fun=pw, arg0=ny)
    fb.op('Add', dst=mt, a=mt, b=dq)
    fb.op('JSGte', a=mt, b=goal, offset='seldone')
    # contest: up to the goal however many armies that takes (no cap / gate stop), all in reach if it isn't met.
    # Not everyone: Harkonnen sent all 21 armies 540 to Eyron (29k besieger, goal 56k) while 850k Fremen closed on
    # Qafiel, where those armies stood
    fb.op('JEq', a=best_mode, b=one, offset='sel')
    fb.op('JSLt', a=b.field(arr, 'length'), b=cap, offset='sel')
    fb.op('JSGte', a=mt, b=gate, offset='seldone')
    fb.op('JAlways', offset='sel')
    fb.label('seldone')
    # the force must still pass the entry ratio on their side incl. aimod_react (the evaluation saw only the
    # start's threat): Smugglers sent 2 S_Troopers (72.6k) at an F_Harvester with a 43.6k F_Trooper able to come
    # (gate 81.7k); contests go short of it (policy §5a goal 2), but not below DEF_HOPE_IN x their side, the
    # defense's own hopeless measure: Atreides sent 1 army (41k) to contest Fanih against a 297k side (gate 446k)
    # and its rally judged Fanih outmatched 2 s later; the rally / Defense own a fight we can't even match
    fb.op('Bool', dst=ok, value=False)
    fb.op('JSGte', a=mt, b=gate, offset='size_ok')
    fb.op('JNotEq', a=best_mode, b=one, offset='fail')
    fb.op('Mul', dst=dq, a=hs, b=_ratio(fb, b, DEF_HOPE_IN))
    fb.op('JSLt', a=mt, b=dq, offset='fail')
    fb.label('size_ok')
    # ... and the battle forecast at the anchor with the selected armies over HUNT_FC_T, the measure the abort pass
    # uses (entry ENTER, a contest DEF_HOPE_IN as above, a restricted chase KILL; abort ABORT): no start that the
    # next check would call weak. Neutral hunts keep their own measure (the forecast counts no foreign raiders)
    fb.op('JEq', a=best_mode, b=two, offset='fc_ok')
    sfc, sneed = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    satk = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=satk, value=True)
    fb.op('Mov', dst=sneed, src=enter)
    fb.op('JNotEq', a=best_mode, b=one, offset='fc_ch')
    fb.op('Bool', dst=satk, value=False)
    fb.op('Mov', dst=sneed, src=_ratio(fb, b, DEF_HOPE_IN))
    fb.op('JAlways', offset='fc_go')
    fb.label('fc_ch')
    fb.op('JTrue', cond=best_far, offset='fc_k')
    fb.op('JNotNull', reg=dfs, offset='fc_k')
    fb.op('JSLte', a=best_t, b=zero, offset='fc_go')
    fb.label('fc_k')
    fb.op('Mov', dst=sneed, src=kill)
    fb.label('fc_go')
    sae = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=sae, src=best_anc)
    fb.op('CallN', dst=sfc, fun=helpers['forecast'], args=[fac, sae, b.const('f64', HUNT_FC_T), satk, arr])
    fb.op('JSLt', a=sfc, b=sneed, offset='fail')
    # task board (rules/board.py, shadow): this launch vs the faction's other open tasks
    bkind = fb.reg(cx.t('String'))
    fb.op('Mov', dst=bkind, src=fb.string('chase'))
    fb.op('JNotEq', a=best_mode, b=one, offset='bk_c')
    fb.op('Mov', dst=bkind, src=fb.string('contest'))
    fb.label('bk_c')
    btg = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=btg, src=best_anc)
    fb.op('JNull', reg=best_g, offset='bk_g')
    fb.op('Mov', dst=btg, src=best_g)
    fb.op('Mov', dst=bkind, src=fb.string('guard'))
    fb.label('bk_g')
    _bd = fb.reg(cx.t('bool'))
    _bk = fb.reg(cx.t('String'))
    fb.op('Mov', dst=_bk, src=bkind)
    _bT = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=_bT, src=b.const('f64', 0))
    _ba = fb.reg(cx.t('hl.types.ArrayObj'))
    fb.op('Mov', dst=_ba, src=arr)
    _bq = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=_bq, value=True)
    _be = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=_be, src=btg)
    fb.op('CallN', dst=_bd, fun=helpers['board'], args=[fac, _bk, _be, sfc, _bT, _ba, _bq])
    fb.op('JFalse', cond=_bd, offset='fail')  # yields to a better task (live kinds only): no start, logged ok false
    fb.label('fc_ok')
    create = cx.fn('logic.ai.$AIEntityGroup.create')
    nul = fb.reg(cx.code.types[create.type.value].definition.args[1].value)
    fb.op('Null', dst=nul)
    grp = fb.reg(cx.t('logic.ai.AIEntityGroup'))
    fb.op('Call2', dst=grp, fun=create.findex.value, arg0=garr, arg1=nul)

    add = cx.fn('logic.ai.AIOrders.addOrder')
    at = [a.value for a in cx.code.types[add.type.value].definition.args]
    kind = fb.reg(cx.t('logic.ai.AIOrderType'))
    fb.op('MakeEnum', dst=kind, construct=MILITARY, args=[])
    fb.op('Mov', dst=ent_r, src=grp)
    nulls = []
    for n in (6, 7, 8, 9, 10):  # sa, mm, om, data, onComplete
        r = fb.reg(at[n])
        fb.op('Null', dst=r)
        nulls.append(r)
    res = fb.reg(cx.t('logic.ai.AIOrder'))
    # a contest may ride a worm (rules/ride.py plan gate, map `wcon` faction -> 1 around the call); a chase never: a
    # moving prey isn't where the worm lands
    wcon = _global_map(fb, b, cx, 'wcon')
    fb.op('JNotEq', a=best_mode, b=one, offset='wc_no')
    b.call('haxe.ds.ObjectMap.set', wcon, fb.dyn(fac), fb.dyn(b.const('i32', 1)))
    fb.label('wc_no')
    fb.op('CallN', dst=res, fun=helpers.get('addOrder', add.findex.value),
          args=[orders_obj, kind, b.const('i32', 5), arr, ent_r, fb.string('ArmyFight')] + nulls)
    b.call('haxe.ds.ObjectMap.remove', wcon, fb.dyn(fac))
    fb.op('Bool', dst=ok, value=False)
    fb.op('JNull', reg=res, offset='fail')
    fb.op('Bool', dst=ok, value=True)
    b.call('haxe.ds.ObjectMap.set', lastmap, fb.dyn(fac), fb.dyn(t))
    fb.op('JNull', reg=best_g, offset='gnorec')
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, 'hgrd'), fb.dyn(res), fb.dyn(best_g))
    fb.label('gnorec')
    fb.op('JNotEq', a=best_mode, b=one, offset='fail')
    b.call('haxe.ds.ObjectMap.set', conmap, fb.dyn(res), fb.dyn(best_anc))  # a contest: abort `won` once it's lifted
    fb.label('fail')
    _log_hunt(fb, b, cx, helpers, fac, 'start', None, best, best_h, best_m,
              {'n': b.field(arr, 'length'), 'ng': b.field(garr, 'length'), 'ok': ok, 'sd': sd, 'dm': best_d,
               'anc': best_anc, 'T': best_t, 'goal': goal, 'gate': gate, 'Ms': mt, 'grd': best_g})
    fb.label('end')
    _crumb_end(fb, b, cx, 'hunt')
    fb.end_try(guard)
    fb.op('Ret', ret=void)
    return fb.build()



