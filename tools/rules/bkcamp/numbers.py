"""Base-kill campaign section: the numbers (D, P, M, the strongest member's M)."""
from rules.common import *  # noqa: F401,F403  thresholds (AI-POLICY §4) and bytecode helpers
from rules import bkstate as bks
from rules.worm import _do_on, _move_to
from rules.bkcamp.shared import *  # noqa: F401,F403

BC_FC_T = 120        # s: the base's defense = the battle forecast's their side at it over this window
BC_D_FRESH = 30      # s: a member's posted defense reading counts this long


def _emit_numbers(c):
    """The numbers: the shared defense reading D, member power P and mustered M, the strongest member's M."""
    (b, bcsg, be, cx, fac, fb, helpers, ld, pw, st, t, zero,) = _take(c, 'b bcsg be cx fac fb helpers ld pw st t zero')
    # the numbers
    dd, mm_, pp, q = (fb.reg(cx.t('f64')) for _ in range(4))
    _fc_theirs(fb, b, cx, helpers, fac, be, dd, T=BC_FC_T)
    # one shared D: every member posts its own reading (fog: Smugglers read 70k while Fremen read 1.5M at the same
    # base, match 2026-10-24 15:00); the phase uses the trimmed mean of the fresh ones (<= BC_D_FRESH s; highest and
    # lowest dropped from 3 or more, the higher of 2, our own alone) (maps `bcd` / `bcdt` faction -> D / when)
    bcd, bcdt = _global_map(fb, b, cx, bks.D_OWN), _global_map(fb, b, cx, bks.D_OWN_T)
    b.call('haxe.ds.ObjectMap.set', bcd, fb.dyn(fac), fb.dyn(dd))
    b.call('haxe.ds.ObjectMap.set', bcdt, fb.dyn(fac), fb.dyn(t))
    dsum, dmax, dmin, dv = (fb.reg(cx.t('f64')) for _ in range(4))
    dn = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=dsum, src=b.const('f64', 0))
    fb.op('Mov', dst=dmax, src=b.const('f64', 0))
    fb.op('Mov', dst=dmin, src=b.const('f64', 1 << 30))
    fb.op('Mov', dst=dn, src=b.const('i32', 0))
    dfs = b.cast(fb.get(st, 'factions', 'array'), 'hl.types.ArrayObj')
    fb.op('JNull', reg=dfs, offset='dd_d')
    dk = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=dk, src=b.const('i32', 0))
    b.loop_head('dd')
    fb.op('JSGte', a=dk, b=b.field(dfs, 'length'), offset='dd_d')
    dfx = b.cast(b.call('hl.types.ArrayObj.getDyn', dfs, dk), 'ent.Faction')
    fb.op('Incr', dst=dk)
    fb.op('JNull', reg=dfx, offset='dd')
    fb.op('JEq', a=dfx, b=ld, offset='dd')
    fb.op('JEq', a=dfx, b=fac, offset='dd_m')
    fb.op('JTrue', cond=b.call('logic.state.State.areAtWar', st, fac, dfx), offset='dd')
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', st, dfx, ld), offset='dd')
    fb.label('dd_m')
    _age(fb, b, cx, bcdt, dfx, t, 'dd', dst=dv)
    fb.op('JSGt', a=dv, b=b.const('f64', BC_D_FRESH), offset='dd')
    ddv = b.call('haxe.ds.ObjectMap.get', bcd, fb.dyn(dfx))
    fb.op('JNull', reg=ddv, offset='dd')
    fb.op('SafeCast', dst=dv, src=ddv)
    fb.op('Add', dst=dsum, a=dsum, b=dv)
    fb.op('Incr', dst=dn)
    fb.op('JSLte', a=dv, b=dmax, offset='dd_x')
    fb.op('Mov', dst=dmax, src=dv)
    fb.label('dd_x')
    fb.op('JSGte', a=dv, b=dmin, offset='dd')
    fb.op('Mov', dst=dmin, src=dv)
    fb.op('JAlways', offset='dd')
    fb.label('dd_d')
    fb.op('JSLt', a=dn, b=b.const('i32', 2), offset='dd_own')
    fb.op('JSGt', a=dn, b=b.const('i32', 2), offset='dd_trim')
    fb.op('Mov', dst=dd, src=dmax)  # two readings: the higher (cautious)
    fb.op('JAlways', offset='dd_own')
    fb.label('dd_trim')
    fb.op('Sub', dst=dsum, a=dsum, b=dmax)
    fb.op('Sub', dst=dsum, a=dsum, b=dmin)
    dnf = fb.reg(cx.t('f64'))
    fb.op('Sub', dst=dn, a=dn, b=b.const('i32', 2))
    fb.op('ToSFloat', dst=dnf, src=dn)
    fb.op('SDiv', dst=dd, a=dsum, b=dnf)
    fb.label('dd_own')
    # the shared D this pass used (heal.py's raze fight retreat reads it: a member's own reading ran 135k-912k for one
    # base, match 70) (map `bcdsh` faction -> D)
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, bks.D_SHARED), fb.dyn(fac), fb.dyn(dd))
    fb.op('Mov', dst=mm_, src=zero)
    fb.op('Mov', dst=pp, src=zero)
    # per member: its power near the base this pass (map `bcpm`, reset each pass): the lead besieges, the rest fight
    bcpm = _global_map(fb, b, cx, bks.NEAR_PW)
    b.call('haxe.ds.ObjectMap.clear', bcpm)
    sarr = b.field(st, 'armies')
    fb.op('JNull', reg=sarr, offset='end')
    k = fb.reg(cx.t('i32'))
    a = _army_loop(fb, b, sarr, b.field(sarr, 'length'), k, 'ma', 'mad')
    ao = b.call('ent.Entity.get_owner', a)
    fb.op('JNull', reg=ao, offset='ma')
    fb.op('JEq', a=ao, b=ld, offset='ma')
    fb.op('JNotNull', reg=b.field(a, 'harvestComponent'), offset='ma')
    fb.op('JEq', a=ao, b=fac, offset='mcount')
    fb.op('JTrue', cond=b.call('logic.state.State.areAtWar', st, fac, ao), offset='ma')  # not a partner of ours
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', st, ao, ld), offset='ma')
    av = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'bkv'), fb.dyn(ao))
    fb.op('JNull', reg=av, offset='m_hum')
    ai = fb.reg(cx.t('i32'))
    fb.op('SafeCast', dst=ai, src=av)
    fb.op('JSLt', a=ai, b=b.const('i32', 2), offset='ma')
    fb.op('JAlways', offset='mcount')
    # a human at truce with us and at war with the leader (no campaign of its own: no `bkv`) helps only where its
    # armies are: within BC_MUSTER_R of B they count in M, never in P (user 2026-10-24: one AI against 3 humans must
    # run the campaign itself; humans join by truce when they want to stop the leader's win)
    fb.label('m_hum')
    fb.op('JTrue', cond=b.call('ent.Faction.get_isAIPlayer', ao), offset='ma')
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', a, be), b=b.const('f64', BC_MUSTER_R), offset='ma')
    fb.op('Call1', dst=q, fun=pw, arg0=a)
    fb.op('Add', dst=mm_, a=mm_, b=q)
    fb.op('JAlways', offset='ma')
    fb.label('mcount')
    fb.op('Call1', dst=q, fun=pw, arg0=a)
    fb.op('Add', dst=pp, a=pp, b=q)
    fb.op('JSLte', a=b.call('ent.Entity.getDistTo', a, be), b=b.const('f64', BC_MUSTER_R), offset='m_in')
    msg = b.call('haxe.ds.ObjectMap.get', bcsg, fb.dyn(ao))
    fb.op('JNull', reg=msg, offset='ma')
    mse = fb.reg(cx.t('ent.Entity'))
    fb.op('SafeCast', dst=mse, src=msg)
    # at the member's staging point or anywhere nearer the base (armies marching in from it stay mustered: the
    # supporters' approach left the staging circle and the 450 ring counted them only on arrival)
    msd = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=msd, src=b.call('ent.Entity.getDistTo', mse, be))
    fb.op('Add', dst=msd, a=msd, b=b.const('f64', BC_STAGE_AT + 50))
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', a, be), b=msd, offset='ma')
    # ... and on the staging side (no farther from the staging point than the base is: else a 1000-far staging made
    # the ring all of the member's land, M = P; review 2026-10-24)
    fb.op('Sub', dst=msd, a=msd, b=b.const('f64', 50))
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', a, mse), b=msd, offset='ma')
    fb.label('m_in')
    fb.op('Add', dst=mm_, a=mm_, b=q)
    pmv = b.call('haxe.ds.ObjectMap.get', bcpm, fb.dyn(ao))
    pmq = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=pmq, src=zero)
    fb.op('JNull', reg=pmv, offset='pm_n')
    fb.op('SafeCast', dst=pmq, src=pmv)
    fb.label('pm_n')
    fb.op('Add', dst=pmq, a=pmq, b=q)
    b.call('haxe.ds.ObjectMap.set', bcpm, fb.dyn(ao), fb.dyn(pmq))
    fb.op('JAlways', offset='ma')
    fb.label('mad')
    # the go ends on the strongest member's M (maps `bcmm` / `bcmmt` faction -> M / when, fresh <= BC_D_FRESH s; match
    # 65: Harkonnen, at war with Fremen, counted only its own 313k and ended the shared go 30 s in, while Fremen's 857k
    # walked in: Fremen's 11 armies turned back to muster)
    bcmm, bcmmt = _global_map(fb, b, cx, bks.M_POST), _global_map(fb, b, cx, bks.M_POST_T)
    b.call('haxe.ds.ObjectMap.set', bcmm, fb.dyn(fac), fb.dyn(mm_))
    b.call('haxe.ds.ObjectMap.set', bcmmt, fb.dyn(fac), fb.dyn(t))
    bcmmb = _global_map(fb, b, cx, bks.M_POST_B)  # ... posted for this base (another campaign's M doesn't count)
    b.call('haxe.ds.ObjectMap.set', bcmmb, fb.dyn(fac), fb.dyn(be))
    gm, gmq = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    fb.op('Mov', dst=gm, src=mm_)
    gmfs = b.cast(fb.get(st, 'factions', 'array'), 'hl.types.ArrayObj')
    fb.op('JNull', reg=gmfs, offset='gm_d')
    gmk = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=gmk, src=b.const('i32', 0))
    b.loop_head('gml')
    fb.op('JSGte', a=gmk, b=b.field(gmfs, 'length'), offset='gm_d')
    gmx = b.call('hl.types.ArrayObj.getDyn', gmfs, gmk)
    fb.op('Incr', dst=gmk)
    gmtv = b.call('haxe.ds.ObjectMap.get', bcmmt, gmx)
    fb.op('JNull', reg=gmtv, offset='gml')
    fb.op('SafeCast', dst=gmq, src=gmtv)
    fb.op('Sub', dst=gmq, a=t, b=gmq)
    fb.op('JSGt', a=gmq, b=b.const('f64', BC_D_FRESH), offset='gml')
    fb.op('JNotEq', a=b.call('haxe.ds.ObjectMap.get', bcmmb, gmx), b=fb.dyn(be), offset='gml')
    gmv = b.call('haxe.ds.ObjectMap.get', bcmm, gmx)
    fb.op('JNull', reg=gmv, offset='gml')
    fb.op('SafeCast', dst=gmq, src=gmv)
    fb.op('JSLte', a=gmq, b=gm, offset='gml')
    fb.op('Mov', dst=gm, src=gmq)
    fb.op('JAlways', offset='gml')
    fb.label('gm_d')
    _give(c, dd=dd, dk=dk, gm=gm, mm_=mm_, pp=pp, q=q, sarr=sarr)
