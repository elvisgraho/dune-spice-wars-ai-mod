"""Base-kill campaign section: the go (re-claims, the lead, the strike point, gather / approach, the foothold hold,
the strike commit)."""
from rules.common import *  # noqa: F401,F403  thresholds (AI-POLICY §4) and bytecode helpers
from rules import bkstate as bks
from rules.worm import _do_on, _move_to
from rules.bkcamp.shared import *  # noqa: F401,F403

BC_ALL_DIRECT = True  # every member razes directly once the force gathered (no Raze orders, no supporter fights)
BC_CUT_STEP = 0.05   # a Raze dead in Waiting: the next try needs armies above its lowest supply share + this
BC_AP_STEP = 25      # strike point: the staging -> base line sampled this often (our land's edge, deep desert)
BC_FAR_STAGE = 500   # go: a member whose strike point lies farther than this from the base runs the muster part
                     # (footholds / stepping stones, staging) instead of razing
BC_EDGE_FAR = 450    # our land's edge farther than this from the base: direct raze ...
BC_EDGE_WAIT = 60    # ... from this many s into the go (the force gathers at the edge first)
BC_AP_AT = 60        # an army this close to the approach point is there
BC_APPROACH = 250    # go: the strike point this far from the base (outside its guns, range 80), on our staging side;
                     # match 35: every Raze from 150 died InvalidRallySlots (the base's buildings leave no free
                     # slots), from 241-332 (matches 33 / 34) they reached Action
BC_RZ_MIN = 200      # a Raze takes no army nearer the base than this (its rally slots would sit among the buildings)
BC_RZ_SUP = 0.6      # ... nor one below this supply share (vanilla: path cost <= 0.7 x the lowest army's supply)
BC_BASE_DEF_R = 300  # supporters also fight the base's militia / garrison this close to it ...
BC_SUP_KEEP = 150    # ... but never a target this close to the base (they'd besiege it: the lead's Raze is cancelled)
BC_RING_K = 1.0      # the lead strikes once the members' ready power >= this x D ...
BC_RING_M = 0.7      # ... or >= this x M (most of the mustered force at the strike points) ...
BC_GATHER_MAX = 150  # ... or this many s into the go (waiting in enemy land drains supply; below BC_GO_MAX: at 240
                     # the go ended in regroup the moment the lead might strike, no Raze in 4 waves, match 00:00)


def _emit_go(c):
    """The go: re-claims, the lead pick, the strike point, gather / approach, the foothold hold, the strike commit."""
    (_ours_claimed, add, at, b, bcgo, bcmc, be, ctrl, cx, dd, fac, fb, free, helpers, j, ld, mlen, mm_, my, n, ok,
     orders, pw, q, sarr, st, stg, t, zero,) = _take(c, '_ours_claimed add at b bcgo bcmc be ctrl cx dd fac fb free helpers j ld mlen mm_ my n ok orders pw q '
        'sarr st stg t zero')
    fb.label('go')
    # every pass of the go, before anything else: our armies in the campaign area (within BC_MUSTER_R of the base,
    # or no farther from it than our staging structure + 200) that are free or still hold our claim are claimed
    # P_RALLY again (a supporter waiting on its running fight returned early and its other armies' claims lapsed
    # after CLAIM_TTL: 11 of Harkonnen's 13 approaching armies went to a prio-1 Liberate of Mim-lon 10 s after the
    # approach, match 2026-10-24 21:37; the lead's armies likewise after its launch)
    gcr = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=gcr, src=b.const('f64', BC_MUSTER_R))
    fb.op('JNull', reg=stg, offset='gc_r')
    gce = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=gce, src=stg)
    gcq = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=gcq, src=b.call('ent.Entity.getDistTo', gce, be))
    fb.op('Add', dst=gcq, a=gcq, b=b.const('f64', BC_STAGE_AT + 50))
    fb.op('JSLte', a=gcq, b=gcr, offset='gc_r')
    fb.op('Mov', dst=gcr, src=gcq)
    fb.label('gc_r')
    gck = fb.reg(cx.t('i32'))
    gca = _army_loop(fb, b, my, mlen, gck, 'gcl', 'gcd')
    fb.op('JNotNull', reg=b.field(gca, 'harvestComponent'), offset='gcl')
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', gca, be), b=gcr, offset='gcl')
    fb.op('Call2', dst=ok, fun=free, arg0=gca, arg1=orders)
    fb.op('JTrue', cond=ok, offset='gc_ok')
    _ours_claimed(gca, 'gc_ok', 'gcl')
    fb.label('gc_ok')
    b.call('haxe.ds.ObjectMap.set', bcmc, fb.dyn(gca), fb.dyn(t))
    gcc = fb.reg(cx.t('bool'))
    fb.op('Call2', dst=gcc, fun=helpers['claim'], arg0=gca, arg1=b.const('f64', P_RALLY))
    fb.op('JAlways', offset='gcl')
    fb.label('gcd')
    gv = b.call('haxe.ds.ObjectMap.get', bcgo, fb.dyn(be))
    fb.op('JNull', reg=gv, offset='end')
    gt = fb.reg(cx.t('f64'))
    fb.op('SafeCast', dst=gt, src=gv)
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, bks.GO_TIME), fb.dyn(fac), fb.dyn(gt))  # heal.py's wave test
    bcl = _global_map(fb, b, cx, bks.LAUNCH)
    lgv = b.call('haxe.ds.ObjectMap.get', bcl, fb.dyn(fac))
    fb.op('JNull', reg=lgv, offset='go_new')
    fb.op('SafeCast', dst=q, src=lgv)
    fb.op('JSLt', a=q, b=gt, offset='go_new')
    # this go launched already: done, unless that Raze died in Waiting (vanilla's supply check: units emptied, phase
    # 1); then our cut (map `bccut` faction -> supply share) rises to the lowest share in it + BC_CUT_STEP and the
    # next try leaves those armies out (vanilla compares the path cost with the lowest army's supply: our straight-line
    # estimate let 12- and 8-army Razes through that it cancelled at once, match 2026-10-24 22:3x)
    lfo = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, bks.LAUNCH_ORDER), fb.dyn(fac))
    # no Raze order (a direct raze sets `bcl` every pass, a Waiting death drops the order): the pass goes on. Ending
    # here stopped every direct raze after its first pass (matches 44-50: one direct row per member per go)
    fb.op('JNull', reg=lfo, offset='go_new')
    lfoo = b.cast(lfo, 'logic.ai.AIOrder')
    fb.op('JSGt', a=b.field(lfoo, 'phase'), b=b.const('i32', 1), offset='end')
    lfu = b.field(lfoo, 'units')
    fb.op('JNull', reg=lfu, offset='lf_dead')
    fb.op('JSGt', a=b.field(lfu, 'length'), b=b.const('i32', 0), offset='end')  # still waiting, alive
    fb.label('lf_dead')
    lmv = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, bks.MIN_SUP), fb.dyn(fac))
    fb.op('JNull', reg=lmv, offset='lf_clr')
    lmq = fb.reg(cx.t('f64'))
    fb.op('SafeCast', dst=lmq, src=lmv)
    fb.op('Add', dst=lmq, a=lmq, b=_ratio(fb, b, BC_CUT_STEP))
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, bks.CUT), fb.dyn(fac), fb.dyn(lmq))
    _log_ev(fb, b, cx, helpers, 'bcamp', [('f', fb.get(fac, 'kind')), ('act', 'cut'), ('tgt', be), ('cut%', lmq)])
    fb.label('lf_clr')
    # the lead stays the lead (`bcl` kept): its next pass razes directly (the cut is set). Dropping it handed the go to
    # another member each time and the direct raze never ran (match 46: Fremen's 3 Waiting deaths, no direct pass)
    b.call('haxe.ds.ObjectMap.remove', _global_map(fb, b, cx, bks.LAUNCH_ORDER), fb.dyn(fac))
    b.call('haxe.ds.ObjectMap.remove', _global_map(fb, b, cx, bks.MIN_SUP), fb.dyn(fac))
    fb.label('go_new')
    garr, rarr, farr = _new_array(fb, b, cx), _new_array(fb, b, cx), _new_array(fb, b, cx)
    gprs = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=gprs, src=b.const('f64', 0))
    gcut, gminr = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    fb.op('Mov', dst=gcut, src=b.const('f64', 0))
    fb.op('Mov', dst=gminr, src=b.const('f64', 2))
    gcv = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, bks.CUT), fb.dyn(fac))
    fb.op('JNull', reg=gcv, offset='gcut_d')
    fb.op('SafeCast', dst=gcut, src=gcv)
    fb.label('gcut_d')
    # the strike point (apx, apy) (march, then strike: user 2026-10-24): the edge of our own land on the line from our
    # staging structure to the base (sampled every BC_AP_STEP, one sample back from the first one off our land, never
    # nearer the base than BC_APPROACH): vanilla's walk plan rallies a structure attack on our own land (cell flag 1,
    # or our airfield range), nearest the order's centroid, with one slot per army there, then prices the supply from
    # there (REVERSING: rally point). Gathered anywhere else, the Raze walked back to our land first and died in
    # Waiting (InvalidRallySlots / InsufficientSupply, matches 32-37). With no staging structure the old point (on the
    # line to the army)
    apok = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=apok, value=False)
    apx, apy = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    fb.op('Mov', dst=apx, src=zero)  # set on every path (read behind `apok` only; bcheck unassigned)
    fb.op('Mov', dst=apy, src=zero)
    fb.op('JNull', reg=stg, offset='ap_d')
    sge = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=sge, src=stg)
    asd = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=asd, src=b.call('ent.Entity.getDistTo', sge, be))
    fb.op('JSLte', a=asd, b=b.const('f64', BC_APPROACH), offset='ap_d')
    fb.op('Mov', dst=apx, src=b.field(sge, 'posx'))
    fb.op('Mov', dst=apy, src=b.field(sge, 'posy'))
    fb.op('Bool', dst=apok, value=True)
    gsw = fb.reg(cx.t('$Game'))
    fb.op('GetGlobal', dst=gsw, **{'global': cx.global_of('$Game')})
    awd = b.field(b.field(gsw, 'inst'), 'world')
    fb.op('JNull', reg=awd, offset='ap_d')
    asx, asy, asf, ass = (fb.reg(cx.t('f64')) for _ in range(4))
    alx, aly = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))  # the last own sample (apx / apy lag one behind it)
    fb.op('Mov', dst=alx, src=apx)
    fb.op('Mov', dst=aly, src=apy)
    fb.op('Mov', dst=ass, src=b.const('f64', BC_AP_STEP))
    b.loop_head('ap')
    fb.op('Sub', dst=asf, a=asd, b=ass)
    fb.op('JSLt', a=asf, b=b.const('f64', BC_APPROACH), offset='ap_d')  # reached BC_APPROACH from the base
    fb.op('SDiv', dst=asf, a=ass, b=asd)
    fb.op('Sub', dst=asx, a=b.field(be, 'posx'), b=b.field(sge, 'posx'))
    fb.op('Mul', dst=asx, a=asx, b=asf)
    fb.op('Add', dst=asx, a=asx, b=b.field(sge, 'posx'))
    fb.op('Sub', dst=asy, a=b.field(be, 'posy'), b=b.field(sge, 'posy'))
    fb.op('Mul', dst=asy, a=asy, b=asf)
    fb.op('Add', dst=asy, a=asy, b=b.field(sge, 'posy'))
    azn = b.call('world.World.getZoneAt', awd, asx, asy)
    fb.op('JNull', reg=azn, offset='ap_d')
    fb.op('JTrue', cond=b.call('ent.Zone.isDeepDesert', azn), offset='ap_d')
    fb.op('JNotEq', a=b.field(azn, 'owner'), b=fac, offset='ap_d')  # off our land
    fb.op('Mov', dst=apx, src=alx)
    fb.op('Mov', dst=apy, src=aly)
    fb.op('Mov', dst=alx, src=asx)
    fb.op('Mov', dst=aly, src=asy)
    fb.op('Add', dst=ass, a=ass, b=b.const('f64', BC_AP_STEP))
    fb.op('JAlways', offset='ap')
    fb.label('ap_d')
    # a foothold: our staging structure within BC_FOOT_NEAR of the base is the strike point (our land: no drain while
    # gathering, healing)
    fb.op('JNull', reg=stg, offset='ap_ft')
    fb.op('JSGt', a=asd, b=b.const('f64', BC_FOOT_NEAR), offset='ap_ft')
    fb.op('Mov', dst=apx, src=b.field(sge, 'posx'))
    fb.op('Mov', dst=apy, src=b.field(sge, 'posy'))
    fb.op('Bool', dst=apok, value=True)
    fb.label('ap_ft')
    # the strike point's zone: routes to it go there, not to our staging structure's zone (match 69: Harkonnen's
    # armies ahead of its staging village were walked back toward it, then forward to the strike point, every pass)
    apz = fb.reg(cx.t('ent.Zone'))
    fb.op('Null', dst=apz)
    fb.op('JFalse', cond=apok, offset='apz_d')
    gsz = fb.reg(cx.t('$Game'))
    fb.op('GetGlobal', dst=gsz, **{'global': cx.global_of('$Game')})
    awz = b.field(b.field(gsz, 'inst'), 'world')
    fb.op('JNull', reg=awz, offset='apz_d')
    fb.op('Mov', dst=apz, src=b.call('world.World.getZoneAt', awz, apx, apy))
    fb.label('apz_d')
    # vanilla's siege supply check (AIOrders estimateSupplyCost > SD_VAN_K x the lowest order army's supply cancels the
    # whole order in Waiting): an army whose walk off our land (min(distance, its + the base's distance to our land)
    # x SUP_U) fails it stays out, a free Supply Drop or not (match 2026-10-24 17:00: Fremen's 24-army Raze at M 2.0M
    # vs D 0.97M died in Waiting 0.3 s after launch, stop src <none>; 19:00: a waiver for a held free drop let an
    # F_Special at supply 39 in, the drop locked to the order and vanilla's check still cancelled it, twice)
    nlow = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=nlow, src=b.const('i32', 0))
    nbusy = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=nbusy, src=b.const('i32', 0))
    ndd = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=ndd, src=b.const('i32', 0))
    gbl = fb.reg(cx.t('f64'))
    fb.op('Call2', dst=gbl, fun=helpers['land'], arg0=fac, arg1=be)
    y = _army_loop(fb, b, my, mlen, j, 'ga', 'gad')
    fb.op('JNotNull', reg=b.field(y, 'harvestComponent'), offset='ga')
    fb.op('JSLte', a=b.call('ent.Entity.getDistTo', y, be), b=b.const('f64', BC_MUSTER_R), offset='ga_in')
    # ... or claimed by the campaign within BC_CLAIM_KEEP s, wherever it is (match 49: the direct raze's armies walking
    # from the strike points were neither near the base nor at staging, garr emptied and every pass ended early)
    gcm = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, bks.SENT), fb.dyn(y))  # sent by the direct raze
    fb.op('JNull', reg=gcm, offset='ga_ncm')
    gcq = fb.reg(cx.t('f64'))
    fb.op('SafeCast', dst=gcq, src=gcm)
    fb.op('Sub', dst=gcq, a=t, b=gcq)
    fb.op('JSLte', a=gcq, b=b.const('f64', BC_CLAIM_KEEP), offset='ga_in')
    fb.label('ga_ncm')
    fb.op('JNull', reg=stg, offset='ga')
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', y, stg), b=b.const('f64', BC_STAGE_AT + 50), offset='ga')
    fb.label('ga_in')
    # present at the strike point (or near the base), busy or not (our campaign fights included): the gather test
    # counts them (map `bcgpr`; Fremen's fighting armies didn't count and the ring read 0.33 x M, match 00:00)
    fb.op('JSLte', a=b.call('ent.Entity.getDistTo', y, be), b=b.const('f64', BC_APPROACH + 60), offset='gpr_in')
    fb.op('JFalse', cond=apok, offset='gpr_d')
    gpx, gpy = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    gpe = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=gpe, src=y)
    _dist2(fb, b, gpe, apx, apy, gpx, gpy)
    fb.op('JSGt', a=gpx, b=b.const('f64', BC_AT_RING * BC_AT_RING), offset='gpr_d')
    fb.label('gpr_in')
    gprq = fb.reg(cx.t('f64'))
    fb.op('Call1', dst=gprq, fun=pw, arg0=y)
    fb.op('Add', dst=gprs, a=gprs, b=gprq)
    fb.label('gpr_d')
    # an army in another order of priority >= BC_PRIO stays out: vanilla addOrder returns null for the whole order
    # when any of its armies is (AIOrders.addOrder busyUnits; match 2026-10-24 20:02: 5 Smugglers fights and a 4-army
    # Raze refused)
    gbk = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=gbk, src=b.field(orders, 'length'))
    b.loop_head('gab')
    fb.op('JSLte', a=gbk, b=b.const('i32', 0), offset='gab_d')
    fb.op('Sub', dst=gbk, a=gbk, b=b.const('i32', 1))
    gbo = b.cast(b.call('hl.types.ArrayObj.getDyn', orders, gbk), 'logic.ai.AIOrder')
    fb.op('JNull', reg=gbo, offset='gab')
    gbu = b.field(gbo, 'units')
    fb.op('JNull', reg=gbu, offset='gab')
    fb.op('JFalse', cond=b.call('hl.types.ArrayObj.contains', gbu, fb.dyn(y)), offset='gab')
    fb.op('JSLt', a=b.field(gbo, 'priority'), b=b.const('i32', BC_PRIO), offset='gab')
    fb.op('Incr', dst=nbusy)
    fb.op('JAlways', offset='ga')
    fb.label('gab_d')
    b.call('hl.types.ArrayObj.push', garr, fb.dyn(y))
    # march, then strike (user 2026-10-24: gating our launches on an estimate of vanilla's supply check shrank every
    # Raze to 1-4 armies): an army at the strike point (within BC_AT_RING) or within BC_APPROACH + 60 of the base is
    # ready (rarr / farr: a short path passes vanilla's check); the rest march there first (`gap`). Our cut after a
    # Raze died in Waiting still applies (its supply share must be above it)
    ye = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=ye, src=y)
    fb.op('JSLte', a=b.call('ent.Entity.getDistTo', ye, be), b=b.const('f64', BC_APPROACH + 60), offset='ga_ring')
    fb.op('JFalse', cond=apok, offset='ga_low')
    grx, gry = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    _dist2(fb, b, ye, apx, apy, grx, gry)
    fb.op('JSGt', a=grx, b=b.const('f64', BC_AT_RING * BC_AT_RING), offset='ga_low')
    fb.label('ga_ring')
    # a Raze never takes an army inside B's own zone (vanilla rallies a structure attack outside the target's zone and
    # searched back out: match 34, Fremen's 1-army Razes at the ring's inner edge died InvalidRallySlots 4 x in 7 s;
    # match 32, 17 x). Fights (army targets) have no such rally: they keep it
    gin = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=gin, value=False)
    fb.op('JEq', a=b.call('ent.Entity.get_zone', ye), b=b.call('ent.Entity.get_zone', be), offset='ga_zi')
    # ... and only from the strike point (our land's edge: vanilla rallies there; an army nearer the base walks back
    # to it first and its path is priced from where it stands)
    fb.op('JFalse', cond=apok, offset='ga_zp')
    gzx, gzy = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    _dist2(fb, b, ye, apx, apy, gzx, gzy)
    fb.op('JSGt', a=gzx, b=b.const('f64', BC_AT_RING * BC_AT_RING), offset='ga_zi')
    fb.label('ga_zp')
    fb.op('JSLt', a=b.call('ent.Entity.getDistTo', ye, be), b=b.const('f64', BC_RZ_MIN), offset='ga_zi')
    fb.op('JSLte', a=b.call('ent.Army.get_maxSupply', y), b=b.const('f64', 0), offset='ga_zo')
    fb.op('JSGte', a=b.call('ent.Army.get_supply', y), b=b.call('ent.Army.get_maxSupply', y), offset='ga_zo')
    gzs = fb.reg(cx.t('f64'))
    fb.op('SDiv', dst=gzs, a=b.call('ent.Army.get_supply', y), b=b.call('ent.Army.get_maxSupply', y))
    fb.op('JSGte', a=gzs, b=_ratio(fb, b, BC_RZ_SUP), offset='ga_zo')
    fb.label('ga_zi')
    fb.op('Bool', dst=gin, value=True)
    fb.label('ga_zo')
    gsr = _supply_share(fb, b, cx, y, 'ga_ok')
    fb.op('JSLte', a=gsr, b=gcut, offset='ga_low')
    fb.op('JSGte', a=gsr, b=gminr, offset='ga_ok')
    fb.op('Mov', dst=gminr, src=gsr)
    fb.op('JAlways', offset='ga_ok')
    fb.label('ga_low')
    fb.op('Incr', dst=nlow)
    fb.op('JAlways', offset='ga')
    fb.label('ga_ok')
    b.call('hl.types.ArrayObj.push', farr, fb.dyn(y))
    fb.op('JTrue', cond=gin, offset='ga')
    b.call('hl.types.ArrayObj.push', rarr, fb.dyn(y))
    fb.op('JAlways', offset='ga')
    fb.label('gad')
    # our go power (the armies that can launch: supply-filtered), posted each pass (maps `bcgp` / `bcgpt` faction ->
    # power / time): the lead is the member with the most of it (match 2026-10-24 19:30: Fremen, strongest near the
    # base by `bcpm`, had no army passing the supply filter, launched nothing and nobody razed)
    gpw, gpq = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    fb.op('Mov', dst=gpw, src=zero)
    gpk = fb.reg(cx.t('i32'))
    gpa = _army_loop(fb, b, rarr, b.field(rarr, 'length'), gpk, 'gp', 'gpd')
    fb.op('Call1', dst=gpq, fun=pw, arg0=gpa)
    fb.op('Add', dst=gpw, a=gpw, b=gpq)
    fb.op('JAlways', offset='gp')
    fb.label('gpd')
    bcgp, bcgpt = _global_map(fb, b, cx, bks.GO_PW), _global_map(fb, b, cx, bks.GO_PW_T)
    b.call('haxe.ds.ObjectMap.set', bcgp, fb.dyn(fac), fb.dyn(gpw))
    b.call('haxe.ds.ObjectMap.set', bcgpt, fb.dyn(fac), fb.dyn(t))
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, bks.GO_PW_NOW), fb.dyn(fac), fb.dyn(gprs))
    # every member posts before anyone acts (the first pass after the go time would crown itself)
    gw = fb.reg(cx.t('f64'))
    fb.op('Sub', dst=gw, a=t, b=gt)
    fb.op('JSLt', a=gw, b=b.const('f64', 2 * BC_T + 1), offset='end')
