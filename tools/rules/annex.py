def build_scoring(cx, new_ids, helpers):
    """Target scores: the single tryAction -> $HScoring.structures(structures, faction, k, ...) call (target
    scores for Annex / Liberate / Pillage / ...) -> wrapper:
    - retry: a structure vanilla launched a siege on less than its block ago is dropped (RETRY, doubled up to
      RETRY_MAX per relaunch right after the block ran out: a launch that keeps failing at once backs off). While its order runs vanilla
      doesn't re-pick it, so a re-pick means that order ended at once: fillAttackSteps cancels in Waiting with
      InsufficientSupply (the lowest army supply < AIOrders.estimateSupplyCost of the path) and the gauge, still
      full, re-picked the same village every ~2.5 s (Fremen Pelmah x39). Logs `space` why retry (10 s throttle);
    - stuck: FAIL_N launches on it within FAIL_WIN that created no order while an army of ours was free to go (map
      `afu` blocked-until, set by the launch wrapper) -> dropped for FAIL_BLOCK..FAIL_MAX s, logs `space` why stuck;
    - next Annex choices (map `akeep`, rules/raid.py annex-keep: top RAID_KEEP within AKEEP_T): no Pillage target;
    - DMZ (rules/dmz.py, aimod_dmzv): Pillage drops a DMZ village, its Annex / Liberate score x DMZ_W;
    - bunker preference: a positive score x BUNKER_W when the structure is within COVER_R of one of our structures
      on our land (their turrets cover each other) or within BUNKER_R of our main base.
    Original scores on any error."""
    orig = cx.fn('logic.ai.$HScoring.structures')
    ft = cx.code.types[orig.type.value].definition
    args = [a.value for a in ft.args]
    fb = FB(cx, args, ft.ret.value, fun_type=orig.type.value)
    b = B(fb)
    res = fb.reg(ft.ret.value)
    fb.op('CallN', dst=res, fun=orig.findex.value, args=list(range(len(args))))
    guard = fb.try_()
    fb.op('JNull', reg=res, offset='end')
    fb.op('JNull', reg=0, offset='end')
    fb.op('JNull', reg=1, offset='end')
    n = b.field(0, 'length')
    # press (rules/strat.py): the gates are opened for the pressed village's owner only; among its villages only the
    # pressed one stays; its Annex score x PRESS_W in annex mode (vanilla picks at random among the top scores), and
    # it is no Annex target in pillage mode (`raid` takes it)
    pvd = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'spv'), fb.dyn(1))
    fb.op('JNull', reg=pvd, offset='nopress')
    pfp = b.cast(b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'spf'), fb.dyn(1)), 'ent.Faction')
    fb.op('JNull', reg=pfp, offset='nopress')
    pab, isann = fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    fb.op('SafeCast', dst=pab, src=b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'spa'), fb.dyn(1)))
    fb.op('Bool', dst=isann, value=True)
    fb.op('JEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Annex'))), b=b.const('i32', 0), offset='pk')
    fb.op('Bool', dst=isann, value=False)
    fb.label('pk')
    pi = fb.reg(cx.t('i32'))
    psc = fb.reg(cx.t('f64'))
    pse = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=pi, src=b.const('i32', 0))
    b.loop_head('ps')
    fb.op('JSGte', a=pi, b=n, offset='nopress')
    pst = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, pi), 'ent.Structure')
    fb.op('Incr', dst=pi)
    fb.op('JNull', reg=pst, offset='ps')
    fb.op('Mov', dst=pse, src=pst)
    fb.op('JNotEq', a=b.call('ent.Entity.get_owner', pse), b=pfp, offset='ps')
    fb.op('JNotEq', a=fb.dyn(pse), b=pvd, offset='pdrop')
    fb.op('JFalse', cond=isann, offset='ps')  # the pressed village: other actions (Pillage, ...) unchanged
    fb.op('JFalse', cond=pab, offset='pdrop')  # pillage mode: not an Annex target (no Authority reserved for it)
    pv0 = b.call('haxe.ds.ObjectMap.get', res, fb.dyn(pse))
    fb.op('JNull', reg=pv0, offset='ps')
    fb.op('SafeCast', dst=psc, src=pv0)
    fb.op('Mul', dst=psc, a=psc, b=b.const('f64', PRESS_W))
    b.call('haxe.ds.ObjectMap.set', res, fb.dyn(pse), fb.dyn(psc))
    fb.op('JAlways', offset='ps')
    fb.label('pdrop')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(pse))
    fb.op('JAlways', offset='ps')
    fb.label('nopress')
    # tension lift (strat_levers): an at-war owner vanilla doesn't target (desiredStatus 0) keeps only the villages
    # that are our contact partners at TEN_GATE (Smugglers' Shariyah / Atreides' Hadnin 113 apart, at war, T at the
    # cap: neither ever listed the other's village)
    dipf = b.field(b.field(1, 'aiController'), 'diplomacy')
    fb.op('JNull', reg=dipf, offset='tgdone')
    tst = _state(fb, b, cx)
    tpf = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'spf'), fb.dyn(1))
    gi, gds = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    gq = fb.reg(cx.t('f64'))
    gse = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=gi, src=b.const('i32', 0))
    b.loop_head('tg')
    fb.op('JSGte', a=gi, b=n, offset='tgdone')
    gst = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, gi), 'ent.Structure')
    fb.op('Incr', dst=gi)
    fb.op('JNull', reg=gst, offset='tg')
    fb.op('Mov', dst=gse, src=gst)
    go = b.call('ent.Entity.get_owner', gse)
    fb.op('JNull', reg=go, offset='tg')
    fb.op('JEq', a=go, b=1, offset='tg')
    fb.op('JEq', a=fb.dyn(go), b=tpf, offset='tg')  # the press owner: handled above
    fb.op('JFalse', cond=b.call('logic.state.State.areAtWar', tst, 1, go), offset='tg')
    fb.op('Int', dst=gds, ptr=cx.code.add_i32(1).value)
    gg = fb.try_()  # throws for a faction the diplomacy module doesn't track
    fb.op('Mov', dst=gds, src=b.call('logic.ai.Diplomacy.getTargetStatus', dipf, go))
    fb.end_try(gg)
    fb.op('JSGte', a=gds, b=b.const('i32', 1), offset='tg')  # vanilla targets it anyway
    fb.op('Call2', dst=gq, fun=helpers['tension'], arg0=1, arg1=gse)
    fb.op('JSGte', a=gq, b=_ratio(fb, b, TEN_GATE), offset='tg')
    tdk = fb.reg(cx.t('bool'))  # a DMZ village (its owner listed for the DMZ): kept, the DMZ step below decides
    fb.op('Call2', dst=tdk, fun=helpers['dmzv'], arg0=1, arg1=gst)
    fb.op('JTrue', cond=tdk, offset='tg')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(gse))
    fb.op('JAlways', offset='tg')
    fb.label('tgdone')
    # our next Annex choices (map `akeep` faction -> village -> time, rules/raid.py annex-keep: top RAID_KEEP within
    # AKEEP_T) are no Pillage targets: vanilla's gauge pillaged Smugglers' top choice (Arslulah x3, Ya-lab), Devastating it and doubling
    # our Annex cost there
    fb.op('JNotEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Pillage'))), b=b.const('i32', 0),
          offset='akdone')
    akv = _fac_map(fb, b, cx, 'akeep', 1)
    ai_, aq, ase = fb.reg(cx.t('i32')), fb.reg(cx.t('f64')), fb.reg(cx.t('ent.Entity'))
    anow = b.field(_state(fb, b, cx), 'time')
    fb.op('Mov', dst=ai_, src=b.const('i32', 0))
    b.loop_head('akl')
    fb.op('JSGte', a=ai_, b=n, offset='akdone')
    ast_ = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, ai_), 'ent.Structure')
    fb.op('Incr', dst=ai_)
    fb.op('JNull', reg=ast_, offset='akl')
    fb.op('Mov', dst=ase, src=ast_)
    # a village of an uncontested deep-desert ring in progress (aimod_ddclean, as raid / the pillage press): no
    # Pillage target either (Fremen's gauge pillaged neutral Alifdad, the village closing their ring, 44:57)
    pdz = b.call('ent.Entity.get_zone', ase)
    fb.op('JNull', reg=pdz, offset='akk')
    pdc = fb.reg(cx.t('bool'))
    fb.op('Call2', dst=pdc, fun=helpers['ddclean'], arg0=1, arg1=pdz)
    fb.op('JFalse', cond=pdc, offset='akk')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(ase))
    _throttle(fb, b, cx, 'pkeep', ase, 60, 'akl')
    _log_ev(fb, b, cx, helpers, 'pkeep', [('f', fb.get(1, 'kind')), ('v', ase)])
    fb.op('JAlways', offset='akl')
    fb.label('akk')
    akt = b.call('haxe.ds.ObjectMap.get', akv, fb.dyn(ase))
    fb.op('JNull', reg=akt, offset='akl')
    fb.op('SafeCast', dst=aq, src=akt)
    fb.op('Sub', dst=aq, a=anow, b=aq)
    fb.op('JSGte', a=aq, b=b.const('f64', AKEEP_T), offset='akl')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(ase))
    fb.op('JAlways', offset='akl')
    fb.label('akdone')
    # DMZ (rules/dmz.py): a border village of an at-war neighbour holding >= DMZ_WAR of them is taken, not burnt:
    # no Pillage target; its Annex / Liberate score x DMZ_W
    dmode = fb.reg(cx.t('i32'))  # 0 other, 1 pillage, 2 annex / liberate
    fb.op('Int', dst=dmode, ptr=cx.code.add_i32(1).value)
    fb.op('JEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Pillage'))), b=b.const('i32', 0), offset='dmk')
    fb.op('Int', dst=dmode, ptr=cx.code.add_i32(2).value)
    fb.op('JEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Annex'))), b=b.const('i32', 0), offset='dmk')
    fb.op('JEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Liberate'))), b=b.const('i32', 0), offset='dmk')
    fb.op('JAlways', offset='dmdone')
    fb.label('dmk')
    di = fb.reg(cx.t('i32'))
    dok = fb.reg(cx.t('bool'))
    dsc = fb.reg(cx.t('f64'))
    dse = fb.reg(cx.t('ent.Entity'))
    fb.op('Mov', dst=di, src=b.const('i32', 0))
    b.loop_head('dml')
    fb.op('JSGte', a=di, b=n, offset='dmdone')
    dst_ = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, di), 'ent.Structure')
    fb.op('Incr', dst=di)
    fb.op('JNull', reg=dst_, offset='dml')
    fb.op('Call2', dst=dok, fun=helpers['dmzv'], arg0=1, arg1=dst_)
    fb.op('JFalse', cond=dok, offset='dml')
    fb.op('Mov', dst=dse, src=dst_)
    fb.op('JNotEq', a=dmode, b=b.const('i32', 1), offset='dmw')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(dse))
    fb.op('JAlways', offset='dml')
    fb.label('dmw')
    dv0 = b.call('haxe.ds.ObjectMap.get', res, fb.dyn(dse))
    fb.op('JNull', reg=dv0, offset='dml')
    fb.op('SafeCast', dst=dsc, src=dv0)
    fb.op('JSLte', a=dsc, b=b.const('f64', 0), offset='dml')
    fb.op('Mul', dst=dsc, a=dsc, b=_ratio(fb, b, DMZ_W))
    b.call('haxe.ds.ObjectMap.set', res, fb.dyn(dse), fb.dyn(dsc))
    fb.op('JAlways', offset='dml')
    fb.label('dmdone')
    mine = b.cast(fb.get(1, 'structures', 'array'), 'hl.types.ArrayObj')
    fb.op('JNull', reg=mine, offset='end')
    mn = b.field(mine, 'length')
    # first spice: an Annex while we own no spice village, faction not SPICE_ANY (they harvest anywhere): its spice
    # villages are never dropped as `stuck` (spice1, per candidate below)
    needsp, spice1 = fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    fb.op('Bool', dst=needsp, value=False)
    spd = _uid('spd')
    fb.op('JNotEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Annex'))), b=b.const('i32', 0), offset=spd)
    skd = b.field(1, 'kind')
    fb.op('JNull', reg=skd, offset=spd)
    for nm in SPICE_ANY:
        fb.op('JEq', a=b.call('String.__compare', skd, fb.dyn(fb.string(nm))), b=b.const('i32', 0), offset=spd)
    snd = fb.get(1, 'cacheData', 'numSpiceVillages')
    fb.op('JNull', reg=snd, offset=spd)
    snp = fb.reg(cx.t('i32'))
    fb.op('SafeCast', dst=snp, src=snd)
    fb.op('JSGt', a=snp, b=b.const('i32', 0), offset=spd)
    fb.op('Bool', dst=needsp, value=True)
    fb.label(spd)
    i, j = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    fb.op('Mov', dst=i, src=b.const('i32', 0))
    zero = b.const('f64', 0)
    cover, br, w = b.const('f64', COVER_R), b.const('f64', BUNKER_R), _ratio(fb, b, BUNKER_W)
    sc, r = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    se, te = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity'))
    now = b.field(_state(fb, b, cx), 'time')
    b.loop_head('s')
    fb.op('JSGte', a=i, b=n, offset='annex')
    s = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, i), 'ent.Structure')
    fb.op('Incr', dst=i)
    fb.op('JNull', reg=s, offset='s')
    fb.op('Mov', dst=se, src=s)
    v = b.call('haxe.ds.ObjectMap.get', res, fb.dyn(se))
    fb.op('JNull', reg=v, offset='s')
    _recent_launch(fb, b, cx, se, now, 'retry', fac=1, helpers=helpers)
    fb.op('Bool', dst=spice1, value=False)
    fb.op('JFalse', cond=needsp, offset='sp1d')
    # neutral only: after a late-game loss the priority returns (vanilla +100, ANNEX_SPICE1), but a spice village held
    # by a strong owner keeps the stuck backoff (no endless re-pick of a target we can't take)
    fb.op('JNotNull', reg=b.call('ent.Entity.get_owner', se), offset='sp1d')
    spz = b.call('ent.Entity.get_zone', se)
    fb.op('JNull', reg=spz, offset='sp1d')
    fb.op('Mov', dst=spice1, src=b.call('ent.Zone.hasSpice', spz))
    fb.label('sp1d')
    # stuck: launches here kept ending without an order (map `afu` = blocked until)
    afu = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'afu'), fb.dyn(se))
    fb.op('JNull', reg=afu, offset='nstk')
    fb.op('SafeCast', dst=r, src=afu)
    fb.op('JSGte', a=now, b=r, offset='nstk')
    # ... not on its first block for our first spice village (user: a faction that needs spice just takes it;
    # SPICE_ANY harvest anywhere). A block that came back (map `afb` doubled past FAIL_BLOCK: it failed again right
    # after) is a real loop (a raider band we can't beat sits there): the backoff applies
    fb.op('JFalse', cond=spice1, offset='stuck')
    afbv = b.call('haxe.ds.ObjectMap.get', _global_map(fb, b, cx, 'afb'), fb.dyn(se))
    fb.op('JNull', reg=afbv, offset='nstk')
    fb.op('SafeCast', dst=r, src=afbv)
    fb.op('JSLte', a=r, b=b.const('f64', FAIL_BLOCK), offset='nstk')
    fb.op('JAlways', offset='stuck')
    fb.label('nstk')
    fb.op('SafeCast', dst=sc, src=v)
    fb.op('JSLte', a=sc, b=zero, offset='s')
    fb.op('Mov', dst=j, src=b.const('i32', 0))
    b.loop_head('m')
    fb.op('JSGte', a=j, b=mn, offset='s')
    t = b.cast(b.call('hl.types.ArrayObj.getDyn', mine, j), 'ent.Structure')
    fb.op('Incr', dst=j)
    fb.op('JNull', reg=t, offset='m')
    fb.op('Mov', dst=te, src=t)
    fb.op('JEq', a=te, b=se, offset='m')
    z = b.call('ent.Entity.get_zone', te)
    fb.op('JNull', reg=z, offset='m')
    fb.op('JNotEq', a=b.field(z, 'owner'), b=1, offset='m')  # on our land (not a UWHeadquarters in theirs)
    fb.op('Mov', dst=r, src=cover)
    fb.op('JFalse', cond=b.call('ent.Structure.get_isMainBase', t), offset='rset')
    fb.op('Mov', dst=r, src=br)
    fb.label('rset')
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', se, te), b=r, offset='m')
    fb.op('Mul', dst=sc, a=sc, b=w)
    b.call('haxe.ds.ObjectMap.set', res, fb.dyn(se), fb.dyn(sc))
    fb.op('JAlways', offset='s')
    fb.label('retry')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(se))
    _throttle(fb, b, cx, 'space', 1, 10, 's')
    near = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=near)
    _log_ev(fb, b, cx, helpers, 'space', [('f', fb.get(1, 'kind')), ('k', 2), ('why', 'retry'), ('tgt', se),
                                          ('near', near)])
    fb.op('JAlways', offset='s')
    fb.label('stuck')
    b.call('haxe.ds.ObjectMap.remove', res, fb.dyn(se))
    _throttle(fb, b, cx, 'space', 1, 10, 's')
    near2 = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=near2)
    _log_ev(fb, b, cx, helpers, 'space', [('f', fb.get(1, 'kind')), ('k', 2), ('why', 'stuck'), ('tgt', se),
                                          ('near', near2)])
    fb.op('JAlways', offset='s')
    fb.label('annex')
    _annex_value(fb, b, cx, helpers, res, mine, mn)
    fb.label('end')
    fb.end_try(guard)
    fb.op('Ret', ret=res)
    wr = fb.build()
    new_ids.add(wr)
    helpers['scores'] = wr  # raid ranks vanilla's Annex choices with the same scores
    return {'bunker-score': _redirect(cx, 'logic.ai.$HScoring.structures', ['logic.ai.AIMilitary.tryAction'], wr)}
