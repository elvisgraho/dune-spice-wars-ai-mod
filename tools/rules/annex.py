"""Siege target scores: Annex value per cost (specials, map centre, compactness, spice opening, Fremen rings,
bunker pairs), retry / stuck / unreach drops, annex-keep and the swap to an affordable pick (`build_scoring`)."""
from rules.common import *  # noqa: F401,F403  thresholds (AI-POLICY §4) and bytecode helpers


def _annex_value(fb, b, cx, helpers, res, mine, mn):
    """Annex only (k = arg 2): value per cost on top of vanilla's score (closure f40995: -10 / zone of distance,
    resource fields in the zone (SpiceArea 40, others 10), region aiWeight (specials 20, Pole 40), main-base
    proximity x Outpost_DistanceCost_MRatio, owned neighbours x 10, +100 for a spice village while we own none; no
    annex cost at all, and tryAction then reserves Authority and waits when the pick is unaffordable). For each
    positive score: vanilla's per-zone distance counts VAN_HOPS_CAP zones at most (the rest added back); + the special
    table (ANNEX_SPECIALS by region id x faction, ANNEX_SPECIALS_EARLY while we own < ANNEX_SP_EARLY_N villages,
    ANNEX_SPECIAL for an unlisted special, Smugglers capped at ANNEX_SP_SMUG_CAP), + ANNEX_SIETCH with a sietch in
    the zone (Zone.getSietch); SPICE_ANY factions lose vanilla's first-spice +100; x (1 + CENTER_W x closeness to the
    map centre = mean village position, 0 at the farthest village; none within CENTER_BASE_R of another faction's main
    base; not for factions without Annex distance cost: Smugglers); factions with distance annex costs x the NEAR_W compactness factor (distance to our nearest structure on our
    land; applied after the ring terms, never below 1 for a feasible ring village: aimod_ddhold); x cmin / cost (real Authority cost: siege.getOccupationActionCost("Annex"), cmin = cheapest candidate:
    a village costing 2 cheap ones counts half); a spice village while we own none x ANNEX_SPICE1 (not SPICE_ANY);
    Fremen deep desert (Zone.updateOwner: a deep desert goes to the single owner of every neighbour with a village
    or main base, if it has DeepDesert_Surounded_GainControl): x (1 + w x min(DD_CAP, sum over unowned deep
    deserts next to the candidate of chance / (1 + neighbours still missing after it))), w = DD_W with the
    attribute, DD_W_PRE for Fremen before it; chance x DD_ENEMY per missing neighbour owned by another faction and
    per one within DD_BASE_R of another faction's main base; 0 when another faction's main base zone borders it;
    x DD_LINK when the candidate borders none of our non-deep-desert zones (reaching it means crossing desert);
    then + DD_ADD x best chance x w (x DD_LINK, x cmin / cost): a flat bonus like ANNEX_SPECIAL. floor ANNEX_FLOOR.
    Focus ring: lowest rank = villages missing (one within DD_BASE_R of another faction's main base or with an at-war
    stack at it, aimod_threat within LOCAL, counts twice) + hops from our main base; the nearer on a tie. A missing
    village under at-war threat also halves the ring's chance (DD_ENEMY), like one held by another faction. Logs `acand` per candidate (v0, hops, sp, cf, cen, dd, c, cmin, s) once per ASCORE_T per faction.
    Top 3: when the best scored is unaffordable now (AIController.getMissingResources of its cost at priority 3 non-empty)
    and the 2nd or 3rd is affordable, the unaffordable ones above it get 0.99 / 0.98 x its score (log `aswap` from, to,
    s); none affordable: vanilla reserves Authority and waits on the best, for ASWAP_WAIT s at most (map `aswt` faction
    -> since when the best is unaffordable): then the best affordable candidate anywhere, every one scored above it
    to 0.98 x its score (log `aswap` with wait). Never the pressed village. Ring hold (same factions): a candidate next to an unowned deep desert is a ring village (map
    'dring' -> now); when a candidate is on an uncontested ring in progress (aimod_ddhold) with fewer than DD_TRIES
    Annex launches (map 'dtries', counted by the launch gate), or one of our armies runs an Annex order on such a
    village, every candidate that isn't a ring village is dropped (Fremen Adur: the spice village was annexed while
    the ring around the uncontested desert was open; dropped, raid pillages it instead). Logs `ascore` (ASCORE_T per
    faction): tgt = our best, s, c (its cost), cmin, vb = vanilla's best (before this), v0 its vanilla score, vs =
    its score now, n candidates, hold = candidates dropped by the ring hold (never the director's pressed village)."""
    fac = 1
    fb.op('JNotEq', a=b.call('String.__compare', 2, fb.dyn(fb.string('Annex'))), b=b.const('i32', 0), offset='end')
    n = b.field(0, 'length')
    zero, big = b.const('f64', 0), b.const('f64', 1 << 30)
    zi = b.const('i32', 0)
    i, j = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    sc, c, cmin, q, d, dm, aw, v0 = (fb.reg(cx.t('f64')) for _ in range(8))
    se, te = fb.reg(cx.t('ent.Entity')), fb.reg(cx.t('ent.Entity'))
    annex = fb.string('Annex')
    gav = cx.fn('ent.Object.getAtbVal')
    gat = [a.value for a in cx.code.types[gav.type.value].definition.args]
    gref, gfac = fb.reg(gat[2]), fb.reg(gat[3])
    fb.op('Null', dst=gref)
    fb.op('Null', dst=gfac)
    gobj = fb.reg(gat[0])
    fb.op('Mov', dst=gobj, src=fac)
    dcr = fb.reg(cx.t('f64'))
    fb.op('Call4', dst=dcr, fun=gav.findex.value, arg0=gobj, arg1=b.const('i32', 952), arg2=gref, arg3=gfac)
    # SPICE_ANY faction? first spice village owned?
    exempt = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=exempt, value=False)
    kd = b.field(fac, 'kind')
    fb.op('JNull', reg=kd, offset='an_kd')
    for nm in SPICE_ANY:
        lbl = _uid('sx')
        fb.op('JNotEq', a=b.call('String.__compare', kd, fb.dyn(fb.string(nm))), b=zi, offset=lbl)
        fb.op('Bool', dst=exempt, value=True)
        fb.label(lbl)
    fb.label('an_kd')
    nsp = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=nsp, src=b.const('i32', 1))
    nsd = fb.get(fac, 'cacheData', 'numSpiceVillages')
    fb.op('JNull', reg=nsd, offset='an_nsp')
    fb.op('SafeCast', dst=nsp, src=nsd)
    fb.label('an_nsp')
    # Fremen deep desert weight: DD_W with DeepDesert_Surounded_GainControl, DD_W_PRE for Fremen before it
    ddw, dd, con, miss, bdd, cmx = (fb.reg(cx.t('f64')) for _ in range(6))
    fb.op('Mov', dst=ddw, src=zero)
    fb.op('Mov', dst=dd, src=zero)
    fb.op('Mov', dst=bdd, src=zero)
    one_f, den = _ratio(fb, b, 1), _ratio(fb, b, DD_ENEMY)
    k1, k2, k3, k4 = (fb.reg(cx.t('i32')) for _ in range(4))
    hm = fb.reg(cx.t('bool'))
    hmb = cx.fn('ent.Zone.hasMainBase')
    hnull = fb.reg(cx.code.types[hmb.type.value].definition.args[1].value)
    fb.op('Null', dst=hnull)
    ddc = helpers['ddhold']
    now = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=now, src=b.field(_state(fb, b, cx), 'time'))
    dring, dtries = _global_map(fb, b, cx, 'dring'), _global_map(fb, b, cx, 'dtries')
    hold, isr, cln = fb.reg(cx.t('bool')), fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    fb.op('Bool', dst=hold, value=False)
    nh = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=nh, src=b.const('i32', 0))
    brest = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=brest)
    brs, brc, brdd, trq = (fb.reg(cx.t('f64')) for _ in range(4))
    for r in (brs, brc, brdd):
        fb.op('Mov', dst=r, src=b.const('f64', 0))
    has = cx.fn('ent.Object.hasAttribute')
    hat = [a.value for a in cx.code.types[has.type.value].definition.args]
    href, hfac = fb.reg(hat[2]), fb.reg(hat[3])
    fb.op('Null', dst=href)
    fb.op('Null', dst=hfac)
    hres = fb.reg(cx.t('bool'))
    fb.op('Call4', dst=hres, fun=has.findex.value, arg0=gobj, arg1=b.const('i32', DD_ATB), arg2=href, arg3=hfac)
    fb.op('JFalse', cond=hres, offset='an_dpre')
    fb.op('Mov', dst=ddw, src=_ratio(fb, b, DD_W))
    fb.op('JAlways', offset='an_dw')
    fb.label('an_dpre')
    fb.op('JNull', reg=kd, offset='an_dw')
    fb.op('JNotEq', a=b.call('String.__compare', kd, fb.dyn(fb.string('Fremen'))), b=zi, offset='an_dw')
    fb.op('Mov', dst=ddw, src=_ratio(fb, b, DD_W_PRE))
    fb.label('an_dw')
    # the ring we work on (lowest rank = villages missing + hops: see an_hok) among unowned deep deserts next to a village that no
    # other faction's main base borders and whose missing villages are all neutral (a held one stalls the ring: it
    # must not halve a clean one); tie: fewest villages missing; the others count x DD_FAR (one ring at a time, not
    # two half-done). No such desert: no focus penalty (hmin 999)
    gdb = cx.fn('ent.Zone.getDistanceToPlayerBase')
    gnull = fb.reg(cx.code.types[gdb.type.value].definition.args[2].value)
    fb.op('Null', dst=gnull)
    hmin, hz = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    fb.op('Mov', dst=hmin, src=b.const('i32', 999))
    mmin, hmis = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))  # mmin = the focus ring's rank (an_hok)
    hthr = fb.reg(cx.t('f64'))
    threat = helpers['threat']
    local_r = b.const('f64', LOCAL)
    fb.op('Mov', dst=mmin, src=big)
    fb.op('JSLte', a=ddw, b=zero, offset='an_hm')
    facs0 = b.cast(fb.get(_state(fb, b, cx), 'factions', 'array'), 'hl.types.ArrayObj')
    k5, k6 = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    hvv = fb.reg(cx.t('ent.Entity'))
    hvl = b.field(_state(fb, b, cx), 'villages')
    fb.op('JNull', reg=hvl, offset='an_hm')
    fb.op('Mov', dst=k1, src=zi)
    b.loop_head('an_hv')
    fb.op('JSGte', a=k1, b=b.field(hvl, 'length'), offset='an_hm')
    hv = b.cast(b.call('hl.types.ArrayObj.getDyn', hvl, k1), 'ent.Entity')
    fb.op('Incr', dst=k1)
    fb.op('JNull', reg=hv, offset='an_hv')
    hvz = b.call('ent.Entity.get_zone', hv)
    fb.op('JNull', reg=hvz, offset='an_hv')
    hvn = b.field(hvz, 'neighbors')
    fb.op('JNull', reg=hvn, offset='an_hv')
    fb.op('Mov', dst=k2, src=zi)
    b.loop_head('an_hw')
    fb.op('JSGte', a=k2, b=b.field(hvn, 'length'), offset='an_hv')
    hdz = b.cast(b.call('hl.types.ArrayObj.getDyn', hvn, k2), 'ent.Zone')
    fb.op('Incr', dst=k2)
    fb.op('JNull', reg=hdz, offset='an_hw')
    fb.op('JFalse', cond=b.call('ent.Zone.isDeepDesert', hdz), offset='an_hw')
    fb.op('JEq', a=b.field(hdz, 'owner'), b=fac, offset='an_hw')
    fb.op('Call3', dst=hz, fun=gdb.findex.value, arg0=hdz, arg1=fac, arg2=gnull)
    hdn = b.field(hdz, 'neighbors')
    fb.op('JNull', reg=hdn, offset='an_hw')
    fb.op('Mov', dst=hmis, src=zero)
    fb.op('Mov', dst=k3, src=zi)
    b.loop_head('an_hx')
    fb.op('JSGte', a=k3, b=b.field(hdn, 'length'), offset='an_hok')
    hmz = b.cast(b.call('hl.types.ArrayObj.getDyn', hdn, k3), 'ent.Zone')
    fb.op('Incr', dst=k3)
    fb.op('JNull', reg=hmz, offset='an_hx')
    fb.op('JEq', a=b.field(hmz, 'owner'), b=fac, offset='an_hx')
    fb.op('Call2', dst=hm, fun=hmb.findex.value, arg0=hmz, arg1=hnull)
    fb.op('JTrue', cond=hm, offset='an_hw')
    fb.op('JNull', reg=b.call('ent.Zone.getVillage', hmz), offset='an_hx')
    fb.op('JNotNull', reg=b.field(hmz, 'owner'), offset='an_hw')  # another faction holds one: stalled, no focus
    fb.op('Add', dst=hmis, a=hmis, b=one_f)
    # a missing village within DD_BASE_R of another faction's main base counts twice (the far end of the map next
    # to its capital: progress there stalls)
    fb.op('JNull', reg=facs0, offset='an_hx')
    fb.op('Mov', dst=hvv, src=b.cast(b.call('ent.Zone.getVillage', hmz), 'ent.Entity'))
    fb.op('JNull', reg=hvv, offset='an_hx')
    _unreach(fb, b, cx, hvv, now, 'an_hw', 1)  # a missing village out of supply reach: this ring can't close, no focus
    # contested: an at-war stack at (or heading to) it counts one more (Fremen's near ring stalled on Aish-Al'nit, 100
    # from Tabr, while Smugglers' 9 armies stood 216-360 from it; vanilla wanted 12 armies there)
    fb.op('Call3', dst=hthr, fun=threat, arg0=fac, arg1=hvv, arg2=local_r)
    fb.op('JSLte', a=hthr, b=zero, offset='an_hnc')
    fb.op('Add', dst=hmis, a=hmis, b=one_f)
    fb.label('an_hnc')
    fb.op('Mov', dst=k5, src=zi)
    b.loop_head('an_hf')
    fb.op('JSGte', a=k5, b=b.field(facs0, 'length'), offset='an_hx')
    hof = b.cast(b.call('hl.types.ArrayObj.getDyn', facs0, k5), 'ent.Faction')
    fb.op('Incr', dst=k5)
    fb.op('JNull', reg=hof, offset='an_hf')
    fb.op('JEq', a=hof, b=fac, offset='an_hf')
    hmbs = b.field(hof, 'mainBases')
    fb.op('JNull', reg=hmbs, offset='an_hf')
    fb.op('Mov', dst=k6, src=zi)
    b.loop_head('an_hg')
    fb.op('JSGte', a=k6, b=b.field(hmbs, 'length'), offset='an_hf')
    hmb2 = b.cast(b.call('hl.types.ArrayObj.getDyn', hmbs, k6), 'ent.Entity')
    fb.op('Incr', dst=k6)
    fb.op('JNull', reg=hmb2, offset='an_hg')
    fb.op('JSGt', a=b.call('ent.Entity.getDistTo', hvv, hmb2), b=b.const('f64', DD_BASE_R), offset='an_hg')
    fb.op('Add', dst=hmis, a=hmis, b=one_f)
    fb.op('JAlways', offset='an_hx')
    fb.label('an_hok')
    # rank = villages missing (one near another faction's main base or under at-war threat counts twice) + hops from
    # our main base: overall the cheapest ring to close, the nearer one on a tie (user: Fremen worked on a ring whose
    # far end was contested while a nearer desert was the better choice). Every desert is ranked (no order-dependent
    # pruning by hops)
    hzf = fb.reg(cx.t('f64'))
    fb.op('ToSFloat', dst=hzf, src=hz)
    fb.op('Add', dst=hzf, a=hzf, b=hmis)
    fb.op('JSLt', a=hzf, b=mmin, offset='an_hset')
    fb.op('JSGt', a=hzf, b=mmin, offset='an_hw')
    fb.op('JSGte', a=hz, b=hmin, offset='an_hw')
    fb.label('an_hset')
    fb.op('Mov', dst=hmin, src=hz)
    fb.op('Mov', dst=mmin, src=hzf)
    fb.op('JAlways', offset='an_hw')
    fb.label('an_hm')
    facs = b.cast(fb.get(_state(fb, b, cx), 'factions', 'array'), 'hl.types.ArrayObj')
    oc = cx.fn('ent.comp.SiegeComponent.getOccupationActionCost')
    oat = [a.value for a in cx.code.types[oc.type.value].definition.args]
    onull = fb.reg(oat[2])
    fb.op('Null', dst=onull)

    def cost_of(st, dst):
        """dst = sum of qty of st's Annex costs for us (0 if unknown)."""
        lbl = _uid('co')
        fb.op('Mov', dst=dst, src=zero)
        sg = b.field(st, 'siege')
        fb.op('JNull', reg=sg, offset=lbl)
        arr = fb.reg(cx.code.types[oc.type.value].definition.ret.value)
        fb.op('Call4', dst=arr, fun=oc.findex.value, arg0=sg, arg1=annex, arg2=onull, arg3=fac)
        fb.op('JNull', reg=arr, offset=lbl)
        k = fb.reg(cx.t('i32'))
        fb.op('Mov', dst=k, src=zi)
        head = _uid('cl')
        b.loop_head(head)
        fb.op('JSGte', a=k, b=b.field(arr, 'length'), offset=lbl)
        qd = fb.get(b.call('hl.types.ArrayObj.getDyn', arr, k), 'qty')
        fb.op('Incr', dst=k)
        fb.op('JNull', reg=qd, offset=head)
        fb.op('SafeCast', dst=q, src=qd)
        fb.op('Add', dst=dst, a=dst, b=q)
        fb.op('JAlways', offset=head)
        fb.label(lbl)

    # map centre = mean village position; crad = the farthest village from it (closeness 0 there)
    cxm, cym, crad, cnt = (fb.reg(cx.t('f64')) for _ in range(4))
    for r in (cxm, cym, crad, cnt):
        fb.op('Mov', dst=r, src=zero)
    cvl = b.field(_state(fb, b, cx), 'villages')
    fb.op('JNull', reg=cvl, offset='cen_d')
    fb.op('Mov', dst=k1, src=zi)
    b.loop_head('cen_a')
    fb.op('JSGte', a=k1, b=b.field(cvl, 'length'), offset='cen_b')
    cv1 = b.cast(b.call('hl.types.ArrayObj.getDyn', cvl, k1), 'ent.Entity')
    fb.op('Incr', dst=k1)
    fb.op('JNull', reg=cv1, offset='cen_a')
    fb.op('Add', dst=cxm, a=cxm, b=b.field(cv1, 'posx'))
    fb.op('Add', dst=cym, a=cym, b=b.field(cv1, 'posy'))
    fb.op('Add', dst=cnt, a=cnt, b=one_f)
    fb.op('JAlways', offset='cen_a')
    fb.label('cen_b')
    fb.op('JSLte', a=cnt, b=zero, offset='cen_d')
    fb.op('SDiv', dst=cxm, a=cxm, b=cnt)
    fb.op('SDiv', dst=cym, a=cym, b=cnt)
    fb.op('Mov', dst=k1, src=zi)
    b.loop_head('cen_c')
    fb.op('JSGte', a=k1, b=b.field(cvl, 'length'), offset='cen_d')
    cv2 = b.cast(b.call('hl.types.ArrayObj.getDyn', cvl, k1), 'ent.Entity')
    fb.op('Incr', dst=k1)
    fb.op('JNull', reg=cv2, offset='cen_c')
    fb.op('Sub', dst=d, a=b.field(cv2, 'posx'), b=cxm)
    fb.op('Mul', dst=d, a=d, b=d)
    fb.op('Sub', dst=q, a=b.field(cv2, 'posy'), b=cym)
    fb.op('Mul', dst=q, a=q, b=q)
    fb.op('Add', dst=d, a=d, b=q)
    fb.op('JSLte', a=d, b=crad, offset='cen_c')
    fb.op('Mov', dst=crad, src=d)
    fb.op('JAlways', offset='cen_c')
    fb.label('cen_d')
    fb.op('Mov', dst=crad, src=b.call('hxd.$Math.sqrt', crad))
    nvil = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=nvil, src=b.field(b.call('ent.Faction.getVillages', fac), 'length'))
    # per-candidate breakdown in this call? (`acand`, once per ASCORE_T per faction)
    logc = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=logc, value=False)
    _throttle(fb, b, cx, 'acand', fac, ASCORE_T, 'acn')
    fb.op('Bool', dst=logc, value=True)
    fb.label('acn')
    vo, spb, cf, cenf, hcf = (fb.reg(cx.t('f64')) for _ in range(5))
    for r in (vo, spb, hcf):
        fb.op('Mov', dst=r, src=zero)
    for r in (cf, cenf):
        fb.op('Mov', dst=r, src=one_f)
    hz2, hzx = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    mx2 = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=hz2, src=zi)
    feas = fb.reg(cx.t('bool'))
    # pass 1: cheapest candidate cost, vanilla's best
    vb = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=vb)
    fb.op('Mov', dst=v0, src=zero)
    fb.op('Mov', dst=cmin, src=big)
    fb.op('Mov', dst=i, src=zi)
    b.loop_head('an1')
    fb.op('JSGte', a=i, b=n, offset='an1d')
    s = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, i), 'ent.Structure')
    fb.op('Incr', dst=i)
    fb.op('JNull', reg=s, offset='an1')
    fb.op('Mov', dst=se, src=s)
    v = b.call('haxe.ds.ObjectMap.get', res, fb.dyn(se))
    fb.op('JNull', reg=v, offset='an1')
    fb.op('SafeCast', dst=sc, src=v)
    fb.op('JEq', a=sc, b=zero, offset='an1')  # 0: vanilla's invalid target; negative: far (hop cap below)
    fb.op('JSLte', a=sc, b=v0, offset='an1c')
    fb.op('Mov', dst=v0, src=sc)
    fb.op('Mov', dst=vb, src=se)
    fb.label('an1c')
    cost_of(s, c)
    fb.op('JSLte', a=c, b=zero, offset='an1')
    fb.op('JSGte', a=c, b=cmin, offset='an1')
    fb.op('Mov', dst=cmin, src=c)
    fb.op('JAlways', offset='an1')
    fb.label('an1d')
    # Annex reserve: the cheapest candidate's Authority cost per faction (maps `acmin` / `acmt` time), read by the
    # Underworld HQ cap (rules/uhq.py) so escalating HQ installs don't eat the next Annex
    acm_lbl = _uid('an_acm')
    fb.op('JSGte', a=cmin, b=big, offset=acm_lbl)
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, 'acmin'), fb.dyn(fac), fb.dyn(cmin))
    acmt_now = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=acmt_now, src=b.field(_state(fb, b, cx), 'time'))
    b.call('haxe.ds.ObjectMap.set', _global_map(fb, b, cx, 'acmt'), fb.dyn(fac), fb.dyn(acmt_now))
    fb.label(acm_lbl)
    # pass 2: rescore
    best = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=best)
    bs, bc = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))
    fb.op('Mov', dst=bs, src=zero)
    fb.op('Mov', dst=bc, src=zero)
    hs = fb.reg(cx.t('bool'))
    fb.op('Mov', dst=i, src=zi)
    b.loop_head('an2')
    fb.op('JSGte', a=i, b=n, offset='an2d')
    s2 = b.cast(b.call('hl.types.ArrayObj.getDyn', 0, i), 'ent.Structure')
    fb.op('Incr', dst=i)
