    hm = fb.reg(cx.t('bool'))
    hmb = cx.fn('ent.Zone.hasMainBase')
    hnull = fb.reg(cx.code.types[hmb.type.value].definition.args[1].value)
    fb.op('Null', dst=hnull)
    ddc = helpers['ddhold']
    now = fb.reg(cx.t('f64'))
    fb.op('Mov', dst=now, src=b.field(_state(fb, b, cx), 'time'))
    dring, dtries = _global_map(fb, b, cx, 'dring'), _global_map(fb, b, cx, 'dtries')
    hold, isr, cln = fb.reg(cx.t('bool')), fb.reg(cx.t('bool')), fb.reg(cx.t('bool'))
    fb.op('Bool', dst=hold, value=False)
    nh = fb.reg(cx.t('i32'))
    fb.op('Mov', dst=nh, src=b.const('i32', 0))
    brest = fb.reg(cx.t('ent.Entity'))
    fb.op('Null', dst=brest)
    brs, brc, brdd, trq = (fb.reg(cx.t('f64')) for _ in range(4))
    for r in (brs, brc, brdd):
        fb.op('Mov', dst=r, src=b.const('f64', 0))
    has = cx.fn('ent.Object.hasAttribute')
    hat = [a.value for a in cx.code.types[has.type.value].definition.args]
    href, hfac = fb.reg(hat[2]), fb.reg(hat[3])
    fb.op('Null', dst=href)
    fb.op('Null', dst=hfac)
    hres = fb.reg(cx.t('bool'))
    fb.op('Call4', dst=hres, fun=has.findex.value, arg0=gobj, arg1=b.const('i32', DD_ATB), arg2=href, arg3=hfac)
    fb.op('JFalse', cond=hres, offset='an_dpre')
    fb.op('Mov', dst=ddw, src=_ratio(fb, b, DD_W))
    fb.op('JAlways', offset='an_dw')
    fb.label('an_dpre')
    fb.op('JNull', reg=kd, offset='an_dw')
    fb.op('JNotEq', a=b.call('String.__compare', kd, fb.dyn(fb.string('Fremen'))), b=zi, offset='an_dw')
    fb.op('Mov', dst=ddw, src=_ratio(fb, b, DD_W_PRE))
    fb.label('an_dw')
    # the ring we work on (fewest villages missing, then fewest hops: see an_hok) among unowned deep deserts next to a village that no
    # other faction's main base borders and whose missing villages are all neutral (a held one stalls the ring: it
    # must not halve a clean one); tie: fewest villages missing; the others count x DD_FAR (one ring at a time, not
    # two half-done). No such desert: no focus penalty (hmin 999)
    gdb = cx.fn('ent.Zone.getDistanceToPlayerBase')
    gnull = fb.reg(cx.code.types[gdb.type.value].definition.args[2].value)
    fb.op('Null', dst=gnull)
    hmin, hz = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    fb.op('Mov', dst=hmin, src=b.const('i32', 999))
    mmin, hmis = fb.reg(cx.t('f64')), fb.reg(cx.t('f64'))  # tie on hops: fewest villages still missing
    fb.op('Mov', dst=mmin, src=big)
    fb.op('JSLte', a=ddw, b=zero, offset='an_hm')
    facs0 = b.cast(fb.get(_state(fb, b, cx), 'factions', 'array'), 'hl.types.ArrayObj')
    k5, k6 = fb.reg(cx.t('i32')), fb.reg(cx.t('i32'))
    hvv = fb.reg(cx.t('ent.Entity'))
    hvl = b.field(_state(fb, b, cx), 'villages')
    fb.op('JNull', reg=hvl, offset='an_hm')
    fb.op('Mov', dst=k1, src=zi)
    b.loop_head('an_hv')
