    exempt = fb.reg(cx.t('bool'))
    fb.op('Bool', dst=exempt, value=False)
    kd = b.field(fac, 'kind')
    fb.op('JNull', reg=kd, offset='an_kd')
    for nm in SPICE_ANY:
        lbl = _uid('sx')
        fb.op('JNotEq', a=b.call('String.__compare', kd, fb.dyn(fb.string(nm))), b=zi, offset=lbl)
        fb.op('Bool', dst=exempt, value=True)
        fb.label(lbl)
