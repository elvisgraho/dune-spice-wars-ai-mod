"""Offline testbed build of both boot files: sha256 of each (a pure refactor must not change them).

Usage: .venv\\Scripts\\python.exe tools\\bhash.py  (from ai-mod; builds from backup/)
       add --save work/refactor-before.json before editing, then --check that file after.
Only --save writes a hash manifest; neither mode installs game files."""
import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

# the build iterates sets / dicts of strings somewhere: with Python's per-process hash randomization two builds of
# the same source differed (2026-10-25), so the hash is only comparable under a fixed seed
if __name__ == '__main__' and os.environ.get('PYTHONHASHSEED') != '0':
    sys.exit(subprocess.call([sys.executable] + sys.argv, env=dict(os.environ, PYTHONHASHSEED='0')))

sys.path.insert(0, str(Path(__file__).resolve().parent))
import boot  # noqa: E402

BOOT_NAMES = ('hlboot.dat', 'hlbootdx.dat')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--save', type=Path, help='save both boot hashes as a new JSON baseline')
    mode.add_argument('--check', type=Path, help='fail if either boot differs from the saved baseline')
    args = parser.parse_args()
    expected = None
    if args.check:
        expected = json.loads(args.check.read_text(encoding='utf-8'))
        if set(expected) != set(BOOT_NAMES):
            parser.error('baseline must contain both hlboot.dat and hlbootdx.dat')
    if args.save and args.save.exists():
        parser.error(f'baseline already exists: {args.save}; choose a new path')

    actual = {}
    for name in BOOT_NAMES:
        out, _ = boot.apply(Path(__file__).resolve().parents[1] / 'backup' / name, ['admin-always-on', 'ai-log'])
        actual[name] = {'sha256': hashlib.sha256(out).hexdigest(), 'size': len(out)}
        print(name, actual[name]['sha256'], len(out), flush=True)
    if args.save:
        args.save.write_text(json.dumps(actual, indent=2) + '\n', encoding='utf-8')
        print(f'Baseline saved: {args.save}')
    if expected is not None:
        changed = [name for name in BOOT_NAMES if actual[name] != expected[name]]
        if changed:
            print('FAIL: generated bytecode changed: ' + ', '.join(changed), file=sys.stderr)
            return 1
        print('PASS: both boot files are byte-identical to the baseline')
    return 0


if __name__ == '__main__':
    sys.exit(main())
